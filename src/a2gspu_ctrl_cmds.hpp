// ---------------------------------------------------------------------------
// THE CPU AND THE REST OF THE MACHINE CAN HAVE DIFFERENT MMUs.
//
// On a IIgs, gs2.cpp wires them apart deliberately:
//
//     computer->cpu->set_mmu(state->mmu_iigs);   // the CPU gets the FPI (8MB)
//     computer->set_mmu(state->mmu_iie);         // everything else, the Mega II
//
// Every verb in this file used rail_mmu(computer), so the whole rail addressed the
// Mega II's 128K while the CPU executed out of the FPI. They are different
// objects over different memory, and nothing said so: `load` acked "loaded 4646
// bytes 00/0400-00/1625", `read` acked the correct bytes back, and the CPU
// fetched zeros and took a BRK on the first instruction. Diagnosed only by
// noticing that 7 cycles with SP dropping 3 is a BRK, not a jump.
//
// The rail's job is to place bytes the CPU will EXECUTE and to read back what
// the CPU can SEE, so it must address the CPU's MMU. On a IIe and every other
// profile the two pointers are the same object and this changes nothing.
// ---------------------------------------------------------------------------
static inline MMU *rail_mmu(computer_t *computer) {
    return (computer && computer->cpu && computer->cpu->mmu) ? computer->cpu->mmu
                                                             : (computer ? computer->mmu : nullptr);
}

// ---------------------------------------------------------------------------
// WHERE THE IIe-STYLE VIDEO MEMORY ACTUALLY IS.
//
// Every video verb -- vram, png, pngc, screen, dhgr-golden -- wants one flat
// 128K image with main at offset 0 and aux at +0x10000, which is what
// MMU_II::get_memory_base() hands back. Each of them obtained it through
// dynamic_cast<MMU_II *>, and MMU_IIgs is NOT in the MMU_II hierarchy, so on a
// IIgs they all reported "no-flat-image" and refused.
//
// That is wrong rather than merely unimplemented: a IIgs displays text, HGR and
// DHGR perfectly well, so there is no reason those verbs should not work there.
//
// The IIgs keeps that image somewhere else. IIe-style video is generated by the
// Mega II out of banks $E0/$E1, and shadowing is what copies $00/$01 writes into
// them -- so the bytes on screen are the Mega II's, not the FPI's. Its image has
// exactly the layout the verbs already expect:
//
//     get_megaii_memory_base() + 0x00000   bank $E0   main
//     get_megaii_memory_base() + 0x10000   bank $E1   aux
//
// the headless spike (a2gspu_spike.cpp) already reads the aux half that way
// ("reads the Mega II bank-$E1 image directly, get_megaii_memory_base()+0x10000"),
// so this is the established route rather than a new theory about the hardware.
//
// Checked in the order it is, because MMU_IIgs must be recognised before the
// MMU_II branch -- not because they overlap today, but because a cast-based
// dispatch that happens to work is how the original bug got in.
// ---------------------------------------------------------------------------
static inline uint8_t *rail_video_base(computer_t *computer) {
    MMU *m = rail_mmu(computer);
    if (!m) return nullptr;
    if (MMU_IIgs *gs = dynamic_cast<MMU_IIgs *>(m)) return gs->get_megaii_memory_base();
    if (MMU_II  *ii = dynamic_cast<MMU_II  *>(m))  return ii->get_memory_base();
    return nullptr;
}

// ---------------------------------------------------------------------------
// The OTHER flat image, and the distinction is the whole point.
//
// rail_video_base above answers "what does the screen show". This answers "what
// does the CPU address" -- and on a IIgs they are different memory:
//
//     get_memory_base()        FPI flat RAM   what 65816 code reads and writes
//     get_megaii_memory_base() Mega II 128K   what IIe-style video is drawn from
//
// Shadowing copies $00/$01 writes into $E0/$E1 for the SHADOWED RANGES ONLY, so
// outside those the two never reconcile. Measured: `load 01:9000` then
// `verify 01:9000` disagreed, because load wrote the FPI image and verify read
// the Mega II one. A rail write that cannot be read back through the rail is
// the one thing read's own comment says an actuator must never be.
//
// So `01:` on load/read/verify means CPU-addressable bank 01 -- aux on a IIe,
// FPI bank $01 on a IIgs -- and the video verbs keep rail_video_base.
//
// IIgs BRANCH FIRST, for the reason the comment above already gives: a
// cast-based dispatch that happens to work is how the original bug got in.
//
// THE REAL DEFECT IS UPSTREAM OF BOTH HELPERS. get_memory_base() is declared
// `virtual` INDEPENDENTLY in MMU_II and MMU_IIgs; the MMU base declares no such
// member, so they are two unrelated virtuals that share a name. That is why
// every caller hand-rolls a cast chain, and why one of them got it wrong.
// Declaring it on MMU would delete this category outright -- worth doing
// deliberately, since the video path must not move with it.
// ---------------------------------------------------------------------------
static inline uint8_t *rail_cpu_ram_base(computer_t *computer) {
    MMU *m = rail_mmu(computer);
    if (!m) return nullptr;
    if (MMU_IIgs *gs = dynamic_cast<MMU_IIgs *>(m)) return gs->get_memory_base();
    if (MMU_II  *ii = dynamic_cast<MMU_II  *>(m))  return ii->get_memory_base();
    return nullptr;
}


