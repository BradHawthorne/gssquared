inline bool parse_addr(const char *s, uint32_t *out) {
    unsigned bank = 0, addr = 0;
    if (sscanf(s, "%x:%x", &bank, &addr) == 2) {
        *out = ((bank & 0xFF) << 16) | (addr & 0xFFFF);
        return true;
    }
    if (sscanf(s, "%x", &addr) == 1) {
        *out = addr & 0xFFFFFF;
        return true;
    }
    return false;
}

// Soft watch state (shared with run/step acks in gs2.cpp).
inline constexpr int SOFT_WATCH_MAX = 16;
struct SoftWatch {
    int n = 0;
    uint32_t addr[SOFT_WATCH_MAX] = {};
    uint8_t prev[SOFT_WATCH_MAX] = {};
    bool armed = false;
};
inline SoftWatch g_soft_watch;

inline void soft_watch_sample(computer_t *computer) {
    if (!rail_mmu(computer) || g_soft_watch.n <= 0) return;
    for (int i = 0; i < g_soft_watch.n; i++)
        g_soft_watch.prev[i] = rail_mmu(computer)->probe_peek(g_soft_watch.addr[i]);
    g_soft_watch.armed = true;
}

inline void soft_watch_after(computer_t *computer, char *buf, size_t bufsz) {
    if (!rail_mmu(computer) || g_soft_watch.n <= 0 || bufsz < 16) return;
    if (!g_soft_watch.armed) {
        soft_watch_sample(computer);
        size_t len = strlen(buf);
        snprintf(buf + len, bufsz - len, " watch=armed n=%d path=probe_peek",
                 g_soft_watch.n);
        return;
    }
    int chg = 0;
    char detail[256] = {0};
    size_t dlen = 0;
    for (int i = 0; i < g_soft_watch.n; i++) {
        uint8_t now = rail_mmu(computer)->probe_peek(g_soft_watch.addr[i]);
        if (now != g_soft_watch.prev[i]) {
            chg++;
            if (dlen + 28 < sizeof detail)
                dlen += (size_t)snprintf(detail + dlen, sizeof detail - dlen,
                                         " %06X:%02X->%02X",
                                         (unsigned)g_soft_watch.addr[i],
                                         (unsigned)g_soft_watch.prev[i],
                                         (unsigned)now);
            g_soft_watch.prev[i] = now;
        }
    }
    size_t len = strlen(buf);
    if (chg)
        snprintf(buf + len, bufsz - len, " watch=CHANGED n=%d%s path=probe_peek",
                 chg, detail);
    else
        snprintf(buf + len, bufsz - len, " watch=stable n=%d path=probe_peek",
                 g_soft_watch.n);
}

inline bool try_watch(const char *line, char *result, size_t rsz, computer_t *computer) {
    if (strncmp(line, "watch ", 6) != 0) return false;
    const char *rest = line + 6;
    while (*rest == ' ') rest++;
    if (!strncmp(rest, "bus", 3) && (rest[3] == 0 || rest[3] == ' ')) {
        const char *b = rest + 3;
        while (*b == ' ') b++;
        if (!strncmp(b, "clear", 5)) {
            g_watch_count = 0;
            g_watch_on = false;
            g_watch_hits = 0;
            snprintf(result, rsz, "status=OK watch bus cleared path=bus_write");
        } else if (!strncmp(b, "list", 4) || !strncmp(b, "hits", 4)) {
            char *p = result;
            size_t rem = rsz;
            int w = snprintf(p, rem,
                "status=OK watch bus n=%d hits=%d on=%d read=%d change=%d path=bus_write",
                g_watch_count, g_watch_hits, g_watch_on ? 1 : 0,
                g_watch_read_on ? 1 : 0, g_watch_change_only ? 1 : 0);
            p += w; rem -= (size_t)w;
            for (int i = 0; i < g_watch_count && rem > 20; i++) {
                w = snprintf(p, rem, " %06X-%06X",
                             g_watch_ranges[i].lo, g_watch_ranges[i].hi);
                p += w; rem -= (size_t)w;
            }
        } else if (!strncmp(b, "read ", 5)) {
            const char *v = b + 5;
            while (*v == ' ') v++;
            g_watch_read_on = (v[0] == '1' || !strncmp(v, "on", 2));
            snprintf(result, rsz, "status=OK watch bus read=%d", g_watch_read_on ? 1 : 0);
        } else if (!strncmp(b, "change ", 7)) {
            const char *v = b + 7;
            while (*v == ' ') v++;
            g_watch_change_only = (v[0] == '1' || !strncmp(v, "on", 2));
            snprintf(result, rsz, "status=OK watch bus change=%d",
                     g_watch_change_only ? 1 : 0);
        } else if (!strncmp(b, "add ", 4)) {
            const char *spec = b + 4;
            while (*spec == ' ') spec++;
            unsigned bank = 0, lo = 0, hi = 0;
            if (sscanf(spec, "%x:%x-%x", &bank, &lo, &hi) != 3 || bank > 0xFF) {
                snprintf(result, rsz,
                         "status=FAIL watch-bus-add need bank:lo-hi");
            } else if (g_watch_count >= 8) {
                snprintf(result, rsz, "status=FAIL watch-bus-full max=8");
            } else {
                g_watch_ranges[g_watch_count].lo = ((bank & 0xFF) << 16) | (lo & 0xFFFF);
                g_watch_ranges[g_watch_count].hi = ((bank & 0xFF) << 16) | (hi & 0xFFFF);
                g_watch_last[g_watch_count] = -1;
                g_watch_count++;
                g_watch_on = true;
                snprintf(result, rsz,
                         "status=OK watch bus add %02X:%04X-%04X n=%d path=bus_write LIVE",
                         bank & 0xFF, lo & 0xFFFF, hi & 0xFFFF, g_watch_count);
            }
        } else {
            snprintf(result, rsz,
                     "status=FAIL watch-bus-need: add|list|hits|clear|read|change");
        }
        return true;
    }
    if (!strncmp(rest, "clear", 5)) {
        g_soft_watch.n = 0;
        g_soft_watch.armed = false;
        snprintf(result, rsz, "status=OK watch soft cleared path=probe_peek");
        return true;
    }
    if (!strncmp(rest, "list", 4) || !strncmp(rest, "sample", 6)) {
        if (!strncmp(rest, "sample", 6) || !g_soft_watch.armed)
            soft_watch_sample(computer);
        char *p = result;
        size_t rem = rsz;
        int w = snprintf(p, rem, "status=OK watch soft n=%d path=probe_peek",
                         g_soft_watch.n);
        p += w; rem -= (size_t)w;
        for (int i = 0; i < g_soft_watch.n && rem > 12; i++) {
            uint8_t v = rail_mmu(computer)
                ? rail_mmu(computer)->probe_peek(g_soft_watch.addr[i]) : 0;
            w = snprintf(p, rem, " %06X=%02X",
                         (unsigned)g_soft_watch.addr[i], (unsigned)v);
            p += w; rem -= (size_t)w;
        }
        return true;
    }
    if (!strncmp(rest, "add ", 4)) {
        const char *a = rest + 4;
        while (*a == ' ') a++;
        uint32_t full = 0;
        unsigned bank = 0, addr = 0;
        bool ok = false;
        if (sscanf(a, "peek:%x:%x", &bank, &addr) == 2) {
            full = ((bank & 0xFF) << 16) | (addr & 0xFFFF);
            ok = true;
        } else if (sscanf(a, "peek:%x", &addr) == 1) {
            full = addr & 0xFFFFFF;
            ok = true;
        } else if (parse_addr(a, &full)) {
            ok = true;
        }
        if (!ok) {
            snprintf(result, rsz, "status=FAIL watch-add-parse");
        } else if (g_soft_watch.n >= SOFT_WATCH_MAX) {
            snprintf(result, rsz, "status=FAIL watch-full");
        } else {
            g_soft_watch.addr[g_soft_watch.n] = full;
            g_soft_watch.prev[g_soft_watch.n] =
                rail_mmu(computer) ? rail_mmu(computer)->probe_peek(full) : 0;
            g_soft_watch.n++;
            g_soft_watch.armed = true;
            snprintf(result, rsz,
                     "status=OK watch soft add peek:%06X n=%d path=probe_peek",
                     (unsigned)full, g_soft_watch.n);
        }
        return true;
    }
    snprintf(result, rsz,
             "status=FAIL watch-need: add|list|sample|clear|bus add|list|hits|clear");
    return true;
}

// Load a flat binary at a 24-bit address through mmu->write (IIe + IIgs).
// Same safety policy as CTRL `load`: refuse I/O $C000 span and bank overrun
// for bank-0 low-address loads. Returns true on success; writes a short
// diagnostic into err (if non-null).
inline bool load_file_at(computer_t *computer, uint32_t addr, const char *path,
                         long *out_n, char *err, size_t errsz) {
    if (!computer || !rail_mmu(computer) || !path || !path[0]) {
        if (err && errsz) snprintf(err, errsz, "no-mmu-or-path");
        return false;
    }
    FILE *f = fopen(path, "rb");
    if (!f) {
        if (err && errsz) snprintf(err, errsz, "open-fail %s", path);
        return false;
    }
    fseek(f, 0, SEEK_END);
    long sz = ftell(f);
    fseek(f, 0, SEEK_SET);
    uint16_t start = (uint16_t)(addr & 0xFFFF);
    long end = (long)start + sz - 1;
    if (sz <= 0) {
        fclose(f);
        if (err && errsz) snprintf(err, errsz, "empty %s", path);
        return false;
    }
    // Only enforce I/O / bank-end guards when the load is in bank 0 and targets
    // the classic 64K map (tile banks at $6000 are safe).
    if (((addr >> 16) & 0xFF) == 0) {
        if (start < 0xD000 && end >= 0xC000) {
            fclose(f);
            if (err && errsz)
                snprintf(err, errsz, "refused crosses I/O $C000 (%ld bytes)", sz);
            return false;
        }
        if (end > 0xFFFF) {
            fclose(f);
            if (err && errsz) snprintf(err, errsz, "refused bank overrun");
            return false;
        }
    }
    long n = 0;
    int c;

    // BANK 1 ON A IIe IS THE AUX 64K.
    //
    // It used to fall through to mmu->write((bank<<16)|addr), which on MMU_II
    // drops the bank bits: `load 01:6000 f` acked "01/6000-01/60FF" and put the
    // bytes at MAIN $6000. An actuator that reports one address and writes
    // another is the worst kind of silent failure, because the ack looks like
    // proof.
    //
    // Aux is reached through the flat image at +0x10000, the same way
    // load_vram_raw and the vram dump already reach it. This is what makes
    // staging a2engine's paged tile banks from the host possible at all: the
    // engine copies main->aux itself, but the lab needs to put three banks there
    // without running the engine three times.
    MMU_II *m2 = dynamic_cast<MMU_II *>(rail_mmu(computer));
    unsigned bank = (addr >> 16) & 0xFF;
    if (m2 && bank == 1) {
        uint8_t *flat = m2->get_memory_base();
        if (!flat) {
            fclose(f);
            if (err && errsz) snprintf(err, errsz, "no flat image for aux");
            return false;
        }
        if (end > 0xFFFF) {
            fclose(f);
            if (err && errsz) snprintf(err, errsz, "refused aux bank overrun");
            return false;
        }
        while ((c = fgetc(f)) != EOF) {
            flat[0x10000 + ((start + n) & 0xFFFF)] = (uint8_t)c;
            n++;
        }
        long abad = -1;                 // same read-back verify as the main path
        rewind(f);
        for (long i = 0; i < n; i++) {
            int want = fgetc(f);
            if (want == EOF) break;
            if (flat[0x10000 + ((start + i) & 0xFFFF)] != (uint8_t)want) {
                abad = i; break;
            }
        }
        fclose(f);
        if (abad >= 0) {
            if (err && errsz)
                snprintf(err, errsz, "aux $%04X reads back wrong after write",
                         (unsigned)((start + abad) & 0xFFFF));
            return false;
        }
        if (out_n) *out_n = n;
        return true;
    }
    if (bank > 1 && m2) {
        // A IIe has two 64K banks and no more. Refusing beats aliasing.
        fclose(f);
        if (err && errsz)
            snprintf(err, errsz, "refused bank %02X: a IIe has bank 0 (main) "
                                 "and bank 1 (aux) only", bank);
        return false;
    }

    // $D000-$FFFF IS ROM UNTIL THE LANGUAGE CARD IS BANKED IN.
    //
    // Writes there were accepted and discarded: `load E000 f` acked OK and
    // $E000 still read $4C 28 F1, which is ROM. Same failure as the bank-1
    // aliasing above -- an actuator reporting success for a write that went
    // nowhere -- and it blocks staging LC-resident code from the host, which is
    // exactly what a2engine needs now that it runs with ROM switched out.
    //
    // Read $C08B twice to select bank 1 with RAM readable and write-enabled.
    // Through mmu->read, not probe_peek: the switch is a side effect, and
    // probe_peek exists precisely to avoid side effects.
    bool lc_banked = false;
    if (bank == 0 && start >= 0xD000) {
        rail_mmu(computer)->read(0xC08B);
        rail_mmu(computer)->read(0xC08B);
        lc_banked = true;
    }

    while ((c = fgetc(f)) != EOF) {
        rail_mmu(computer)->write(
            (uint32_t)((addr & 0xFF0000) | ((start + n) & 0xFFFF)),
            (uint8_t)c);
        n++;
    }

    // VERIFY BY READING BACK. Both silent-load bugs found in this rail -- bank 1
    // aliasing to main, and $D000+ vanishing into ROM -- would have been caught
    // here for the cost of one pass over the data. A load that cannot show the
    // bytes arrived has not loaded anything, it has only reported.
    long bad = -1;
    rewind(f);
    for (long i = 0; i < n; i++) {
        int want = fgetc(f);
        if (want == EOF) break;
        uint8_t got = rail_mmu(computer)->probe_peek(
            (uint32_t)((addr & 0xFF0000) | ((start + i) & 0xFFFF)));
        if (got != (uint8_t)want) { bad = i; break; }
    }
    fclose(f);
    if (bad >= 0) {
        if (err && errsz)
            snprintf(err, errsz,
                     "wrote %ld byte(s) but $%04X reads back wrong%s -- "
                     "nothing is backing that address",
                     n, (unsigned)((start + bad) & 0xFFFF),
                     lc_banked ? " even with the language card banked in" : "");
        return false;
    }
    if (out_n) *out_n = n;
    return true;
}

// Parse one LOAD entry: "file@HEX" (RUN_BIN style) or "HEX@file" / "BB:AAAA@file".
// Returns true and fills addr + pathbuf.
inline bool parse_load_spec(const char *spec, uint32_t *addr, char *pathbuf,
                            size_t pathsz) {
    if (!spec || !spec[0] || !addr || !pathbuf || pathsz < 2) return false;
    // Find last '@' so Windows drive letters don't confuse "C:\path@6000"
    const char *at = strrchr(spec, '@');
    if (!at || at == spec || !at[1]) return false;
    size_t left_len = (size_t)(at - spec);
    char left[512], right[512];
    if (left_len >= sizeof left) return false;
    memcpy(left, spec, left_len);
    left[left_len] = 0;
    strncpy(right, at + 1, sizeof right - 1);
    right[sizeof right - 1] = 0;
    // Trim spaces
    auto trim = [](char *s) {
        while (*s == ' ' || *s == '\t') s++;
        char *e = s + strlen(s);
        while (e > s && (e[-1] == ' ' || e[-1] == '\t')) *--e = 0;
        return s;
    };
    char *L = trim(left);
    char *R = trim(right);
    uint32_t a = 0;
    // Prefer path@addr when right side parses as address and left looks like a path
    // (contains / \ . or is longer than 6 hex chars without colon bank form).
    bool right_addr = parse_addr(R, &a);
    bool left_addr = parse_addr(L, &a);
    if (right_addr && (!left_addr || strchr(L, '/') || strchr(L, '\\') ||
                       strchr(L, '.') || strlen(L) > 8)) {
        *addr = 0;
        parse_addr(R, addr);
        strncpy(pathbuf, L, pathsz - 1);
        pathbuf[pathsz - 1] = 0;
        return true;
    }
    if (left_addr) {
        *addr = 0;
        parse_addr(L, addr);
        strncpy(pathbuf, R, pathsz - 1);
        pathbuf[pathsz - 1] = 0;
        return true;
    }
    return false;
}

// Load 16K vram-raw (8K AUX then 8K MAIN) into MMU_II flat image at HGR page.
// page 1 → $2000, page 2 → $4000. Matches CTRL `vram` dump layout and
// a2tile page.paint / dhgr-golden vram-raw.
inline bool load_vram_raw(computer_t *computer, const char *path, int page,
                          char *err, size_t errsz) {
    if (!computer || !rail_mmu(computer) || !path || !path[0]) {
        if (err && errsz) snprintf(err, errsz, "no-mmu-or-path");
        return false;
    }
    if (page != 2) page = 1;
    uint32_t base = (page == 2) ? 0x4000u : 0x2000u;
    uint8_t *flat = rail_video_base(computer);
    if (!flat) {
        if (err && errsz) snprintf(err, errsz, "no-flat-image");
        return false;
    }
    FILE *f = fopen(path, "rb");
    if (!f) {
        if (err && errsz) snprintf(err, errsz, "open-fail %s", path);
        return false;
    }
    uint8_t buf[0x4000];
    size_t n = fread(buf, 1, sizeof buf, f);
    fclose(f);
    if (n != sizeof buf) {
        if (err && errsz)
            snprintf(err, errsz, "need 16384 bytes, got %zu from %s", n, path);
        return false;
    }
    memcpy(flat + 0x10000 + base, buf, 0x2000);       // AUX
    memcpy(flat + base, buf + 0x2000, 0x2000);         // MAIN
    return true;
}

// Apply A2GSPU_LOAD env: comma/semicolon-separated specs. Prints per-entry status.
// Returns true if every entry succeeded (or env empty). Hard-fails open/policy errors.
inline bool apply_env_loads(computer_t *computer, const char *env) {
    if (!env || !env[0]) return true;
    char buf[4096];
    strncpy(buf, env, sizeof buf - 1);
    buf[sizeof buf - 1] = 0;
    int ok_n = 0, fail_n = 0;
    char *save = nullptr;
    // Split on ; or ,
    for (char *p = buf; *p;) {
        while (*p == ' ' || *p == '\t' || *p == ',' || *p == ';') p++;
        if (!*p) break;
        char *start = p;
        while (*p && *p != ',' && *p != ';') p++;
        char save_c = *p;
        *p = 0;
        uint32_t addr = 0;
        char path[1024];
        char err[256];
        if (!parse_load_spec(start, &addr, path, sizeof path)) {
            printf("A2GSPU LOAD: FAIL parse '%s' (need file@HEX or HEX@file)\n", start);
            fail_n++;
        } else {
            long n = 0;
            if (load_file_at(computer, addr, path, &n, err, sizeof err)) {
                printf("A2GSPU LOAD: OK %ld byte(s) @%02X/%04X from %s "
                       "(DELIBERATE splice)\n",
                       n, (unsigned)((addr >> 16) & 0xFF),
                       (unsigned)(addr & 0xFFFF), path);
                ok_n++;
            } else {
                printf("A2GSPU LOAD: FAIL %s @%06X: %s\n", path, (unsigned)addr, err);
                fail_n++;
            }
        }
        if (!save_c) break;
        *p = save_c;
        p++;
        (void)save;
    }
    printf("A2GSPU LOAD: summary ok=%d fail=%d\n", ok_n, fail_n);
    if (ok_n == 0 && fail_n == 0) {
        printf("A2GSPU LOAD: FAIL empty spec list\n");
        return false;
    }
    return fail_n == 0 && ok_n > 0;
}

inline bool try_inject(const char *line, char *result, size_t rsz, computer_t *computer) {
    if (!strncmp(line, "poke ", 5)) {
        uint32_t addr = 0;
        int off = 0;
        char abuf[64];
        if (sscanf(line + 5, "%63s %n", abuf, &off) == 1 && parse_addr(abuf, &addr)) {
            // AN EXPLICIT BANK BYPASSES THE SOFT SWITCHES.
            //
            // poke wrote through mmu->write(), which honours RAMRD/RAMWRT as the
            // GUEST last left them, and then reported the bank it had been ASKED
            // for rather than the one it actually hit. After a DHGR frame the
            // tile blitter leaves RAMWRT pointing at aux, so `poke A100 5A` put
            // the byte in AUX $A100 and acked "@00/A100" -- a splice landing
            // somewhere the caller did not choose, reported as if it had not.
            //
            // `read` and `load` already accept BB:AAAA and go straight to the
            // flat image for exactly this reason. This is the third of three.
            // Bare `poke AAAA` still goes through the MMU: writing soft switches
            // and I/O at $C0xx is a legitimate use that must reach the handlers.
            const bool banked = (strchr(abuf, ':') != nullptr);
            const unsigned bank = (addr >> 16) & 0xFF;
            MMU_II *m2w = banked ? dynamic_cast<MMU_II *>(rail_mmu(computer)) : nullptr;
            uint8_t *flat = m2w ? m2w->get_memory_base() : nullptr;
            // NOT AN MMU_II IS NOT THE SAME AS NO BANKS. A IIgs MMU has eight
            // megabytes of them; it simply is not in the MMU_II hierarchy, so the
            // flat-image shortcut does not apply. probe_poke is the polymorphic
            // route that every MMU implements, and MMU_IIgs resolves banks
            // $00/$01 through the same aux calculation its handler pages use.
            const bool use_probe = banked && !flat;
            if (banked && flat && bank > 1) {
                snprintf(result, rsz, "status=FAIL poke-bank-unavailable");
                return true;
            }
            const char *p = line + 5 + off;
            int n = 0;
            while (*p) {
                while (*p == ' ' || *p == ',') p++;
                if (!*p) break;
                char *end = nullptr;
                unsigned long v = strtoul(p, &end, 16);
                if (end == p) break;
                if (flat)
                    flat[(bank == 1 ? 0x10000u : 0u) +
                         (((addr & 0xFFFF) + n) & 0xFFFF)] = (uint8_t)(v & 0xFF);
                else if (use_probe)
                    rail_mmu(computer)->probe_poke(addr + n, (uint8_t)(v & 0xFF));
                else
                    rail_mmu(computer)->write(addr + n, (uint8_t)(v & 0xFF));
                n++;
                p = end;
            }
            // NAME THE BANK THAT WAS ACTUALLY WRITTEN. This said "main" for
            // anything that was not bank 1, so a IIgs `poke E1:9E00` -- a write
            // into super hi-res palette memory -- acked "@main $9E00". The whole
            // reason this verb reports a bank is that it once wrote one bank
            // while claiming another; naming only two of eight million is the
            // same failure with a smaller radius.
            if (n) {
                char where[24];
                if (!banked)              snprintf(where, sizeof where, "live-banks");
                else if (bank == 0)       snprintf(where, sizeof where, "main");
                else if (bank == 1)       snprintf(where, sizeof where, "aux");
                else                      snprintf(where, sizeof where, "bank $%02X", bank);
                snprintf(result, rsz,
                         "status=OK poked %d byte(s) @%s $%04X (DELIBERATE splice)",
                         n, where, (unsigned)(addr & 0xFFFF));
            }
            else
                snprintf(result, rsz, "status=FAIL poke-no-bytes");
        } else {
            snprintf(result, rsz, "status=FAIL poke-parse-fail");
        }
        return true;
    }
    if (!strncmp(line, "vram ", 5)) {
        // vram <file> [page]           — dump 16K aux‖main
        // vram load <file> [page]      — inject 16K aux‖main (a2tile offline paint)
        char fbuf[512];
        int page = 1;
        char cmd[16] = {0};
        if (sscanf(line + 5, "%15s %511s %d", cmd, fbuf, &page) >= 2 &&
            !strcmp(cmd, "load")) {
            if (page != 2) page = 1;
            char err[256];
            if (load_vram_raw(computer, fbuf, page, err, sizeof err))
                snprintf(result, rsz,
                         "status=OK vram load profile=vram-raw page%d 16384 "
                         "aux+main from %s (DELIBERATE splice)",
                         page, fbuf);
            else
                snprintf(result, rsz, "status=FAIL vram-load-%s", err);
            return true;
        }
        page = 1;
        if (sscanf(line + 5, "%511s %d", fbuf, &page) >= 1) {
            if (page != 2) page = 1;
            uint32_t base = (page == 2) ? 0x4000u : 0x2000u;
            const uint8_t *flat = rail_video_base(computer);
            FILE *vf = flat ? fopen(fbuf, "wb") : nullptr;
            if (!flat) {
                snprintf(result, rsz, "status=FAIL vram-no-flat-image");
            } else if (!vf) {
                snprintf(result, rsz, "status=FAIL vram-open-fail %s", fbuf);
            } else {
                fwrite(flat + 0x10000 + base, 1, 0x2000, vf);
                fwrite(flat + base, 1, 0x2000, vf);
                fclose(vf);
                /* 16384, not 8192: two 0x2000 halves are written, and the ack
                 * reported one of them. A caller comparing the number against
                 * a2tile's 16384-byte page.vram would conclude the dump was
                 * truncated and go looking for a bug that is not there. The
                 * count an actuator reports must be the count it wrote. */
                snprintf(result, rsz,
                         "status=OK vram profile=vram-raw page%d 16384 "
                         "(8192 aux + 8192 main) -> %s",
                         page, fbuf);
            }
        } else {
            snprintf(result, rsz, "status=FAIL vram-parse-fail");
        }
        return true;
    }
    if (!strncmp(line, "load ", 5)) {
        uint32_t addr = 0;
        char abuf[64], fbuf[512];
        if (sscanf(line + 5, "%63s %511s", abuf, fbuf) == 2 && parse_addr(abuf, &addr)) {
            long n = 0;
            char err[256];
            if (load_file_at(computer, addr, fbuf, &n, err, sizeof err)) {
                uint16_t start = (uint16_t)(addr & 0xFFFF);
                snprintf(result, rsz,
                         "status=OK loaded %ld byte(s) %02X/%04lX-%02X/%04lX from %s "
                         "(DELIBERATE splice)",
                         n, (unsigned)((addr >> 16) & 0xFF), (unsigned long)start,
                         (unsigned)((addr >> 16) & 0xFF),
                         (unsigned long)(start + n - 1), fbuf);
            } else {
                snprintf(result, rsz, "status=FAIL load-%s", err);
            }
        } else {
            snprintf(result, rsz,
                     "status=FAIL load-parse-fail (need: load <addr> <file>)");
        }
        return true;
    }
    return false;
}

inline bool try_visual(const char *line, char *result, size_t rsz, computer_t *computer) {
    // ---- shr <file> [scale] -- the IIgs super hi-res screen -----------------
    //
    // THERE WAS NO WAY TO SEE A IIgs SCREEN. png/pngc/vram are all HGR/DHGR and
    // gated on an MMU_II cast a IIgs MMU cannot satisfy, so the single most
    // productive debugging technique available -- looking at what a human would
    // see -- did not exist on that platform at all. Every silent bug found in
    // this project was found by looking at output, never by a check.
    //
    // SHR is refreshingly simple after HGR: a LINEAR framebuffer, no row-address
    // scramble, no artifact colour, no bank interleave.
    //
    //   $E12000  32,000 bytes   200 lines x 160, two 4-bit pixels per byte
    //   $E19D00  200 bytes      one scanline control byte per line
    //   $E19E00  512 bytes      16 palettes x 16 entries x 2 bytes
    //
    // SCB bits 0-3 select the palette for that line, bit 7 selects 640 mode.
    // A palette entry is little-endian $0RGB, four bits each, scaled by 17 to
    // reach 8-bit -- so $F becomes $FF rather than $F0 and white is white.
    if (!strncmp(line, "shr ", 4)) {
        char fbuf[512]; int scale = 3;
        int got = sscanf(line + 4, "%511s %d", fbuf, &scale);
        if (got < 1) { snprintf(result, rsz, "status=FAIL shr-parse-fail"); return true; }
        if (scale < 1 || scale > 8) scale = 3;
        MMU *m = rail_mmu(computer);
        if (!m) { snprintf(result, rsz, "status=FAIL shr-no-mmu"); return true; }

        static uint8_t pix[32000], scb[200], pal[512];
        for (int i = 0; i < 32000; i++) pix[i] = m->probe_peek(0xE12000u + i);
        for (int i = 0; i < 200;   i++) scb[i] = m->probe_peek(0xE19D00u + i);
        for (int i = 0; i < 512;   i++) pal[i] = m->probe_peek(0xE19E00u + i);

        // THE MODE IS PER LINE, not per screen: bit 7 of each SCB. A IIgs can
        // and does mix 320- and 640-mode lines in one frame, so rendering the
        // whole screen in whichever mode line 0 happens to use would be wrong on
        // exactly the screens worth looking at.
        //
        // Render 640 wide only when some line actually asks for it, and double
        // the 320-mode lines into it -- both modes occupy the same physical
        // width on real hardware. An all-320 screen still comes out 320 wide, so
        // callers written against the previous behaviour are unaffected.
        bool any640 = false;
        for (int y = 0; y < 200; y++) if (scb[y] & 0x80) { any640 = true; break; }

        // 640 mode packs four 2-bit pixels per byte against a SPLIT palette, and
        // the group offsets are deliberately not uniform: leftmost pixel takes
        // entries 8-11, then 12-15, then 0-3, then 4-7. That arrangement is what
        // makes 640-mode dithering produce more than four colours.
        //
        // Taken from the emulator's OWN scan generator rather than from memory
        // -- VideoScanGenerator.cpp emits pixel640<3>+0x8, <2>+0xC, <1>+0x0,
        // <0>+0x4 -- so this verb and the thing on screen agree by construction
        // instead of by two independent recollections of the hardware. (My own
        // recollection of the group order was wrong; the source was not.)
        static const int sh640[4]  = { 6, 4, 2, 0 };
        static const int off640[4] = { 8, 12, 0, 4 };

        const int PW = any640 ? 640 : 320;
        const int W = PW * scale, H = 200 * scale;
        std::vector<uint8_t> rgb((size_t)W * H * 3);

        // "lit" COUNTS SOURCE PIXELS, NOT OUTPUT PIXELS, and that distinction is
        // load-bearing. A 320 line drawn into a 640 frame occupies two output
        // columns, so counting output would DOUBLE the figure the moment some
        // unrelated line switched the frame to 640 -- which is exactly what
        // happened: railcheck lights 160 pixels, asks for the count to move by
        // 160, and got 320 because a single uninitialised SCB byte had bit 7 set
        // and widened the whole frame. The screen had not changed at all.
        //
        // Counting source pixels makes the number mean "how much of SHR memory
        // is non-background", which is what a caller is actually asking, and
        // makes it independent of a geometry decision taken elsewhere.
        int lit = 0, total = 0;
        for (int y = 0; y < 200; y++) {
            const uint8_t s = scb[y];
            const int pbase = (s & 0x0F) * 32;
            const bool m640 = (s & 0x80) != 0;
            total += m640 ? 640 : 320;
            for (int px = 0; px < PW; px++) {
                int idx;
                if (m640) {
                    const int g = px & 3;
                    const uint8_t byte = pix[y * 160 + (px >> 2)];
                    const int v = (byte >> sh640[g]) & 3;
                    idx = off640[g] + v;
                    // "lit" must mean "not the background colour". In 640 mode
                    // idx carries a non-zero group offset even for value 0, so
                    // counting idx would report a blank screen as full.
                    if (v) lit++;
                } else {
                    const int x = any640 ? (px >> 1) : px;   // 320 line, 640 frame
                    const uint8_t byte = pix[y * 160 + (x >> 1)];
                    idx = (x & 1) ? (byte & 0x0F) : (byte >> 4);
                    // only on the first of the doubled pair -- see above
                    if (idx && (!any640 || !(px & 1))) lit++;
                }
                const uint8_t lo = pal[pbase + idx * 2], hi = pal[pbase + idx * 2 + 1];
                const uint8_t r = (uint8_t)((hi & 0x0F) * 17);
                const uint8_t g8 = (uint8_t)((lo >> 4) * 17);
                const uint8_t b = (uint8_t)((lo & 0x0F) * 17);
                for (int sy = 0; sy < scale; sy++) {
                    uint8_t *row = &rgb[((size_t)(y * scale + sy) * W + (size_t)px * scale) * 3];
                    for (int sx = 0; sx < scale; sx++) { row[sx*3+0]=r; row[sx*3+1]=g8; row[sx*3+2]=b; }
                }
            }
        }
        // Same path handling as png/pngc in this file: the filename as given.
        if (a2png::write_rgb(fbuf, rgb.data(), W, H))
            snprintf(result, rsz, "status=OK shr %s %dx%d scale%d nonzero=%d/%d -> %s",
                     any640 ? "640" : "320", W, H, scale, lit, total, fbuf);
        else
            snprintf(result, rsz, "status=FAIL shr-write-fail");
        return true;
    }
    if (!strncmp(line, "png ", 4)) {
        char fbuf[512];
        // PAGE 0 MEANS "THE ONE ON SCREEN", and it is the default.
        //
        // `png f 1` renders page 1 whether or not page 1 is being displayed. On a
        // double-buffered guest that is a coin flip, and the failure is silent:
        // you get a real, plausible, one-frame-stale picture and believe it. It
        // cost two wrong conclusions in one debugging session -- a dialogue screen
        // that looked like it had not opened, and a message log that looked like
        // it had not updated. The live page is knowable (`vid` prints PAGE2), so
        // asking for it should not be something a caller has to remember.
        int page = 0, scale = 3;
        char mbuf[16] = "auto";
        if (sscanf(line + 4, "%511s %d %d %15s", fbuf, &page, &scale, mbuf) >= 1) {
            if (page == 0) {
                display_state_t *lds = (display_state_t *)computer->cached_display_state;
                VideoScannerII *lvs = lds ? lds->video_scanner : nullptr;
                page = (lvs && lvs->is_page_2()) ? 2 : 1;
            }
            if (page != 2) page = 1;
            if (scale < 1) scale = 1;
            if (scale > 8) scale = 8;
            uint32_t base = (page == 2) ? 0x4000u : 0x2000u;
            bool dbl = false;
            display_state_t *pds = (display_state_t *)computer->cached_display_state;
            VideoScannerII *pvs = pds ? pds->video_scanner : nullptr;
            if (!strcmp(mbuf, "dhgr"))
                dbl = true;
            else if (!strcmp(mbuf, "hgr"))
                dbl = false;
            else if (pvs)
                dbl = pvs->is_dblres() && pvs->is_80col();
            const uint8_t *flat = rail_video_base(computer);
            if (dbl && !flat) dbl = false;
            const int W = dbl ? 560 : 280, H = 192;
            const int bpc = dbl ? 14 : 7;
            const int sxn = scale, syn = dbl ? scale * 2 : scale;
            int ow = W * sxn, oh = H * syn;
            std::vector<uint8_t> img((size_t)ow * oh, 0);
            long lit = 0;
            for (int y = 0; y < H; y++) {
                for (int cx = 0; cx < 40; cx++) {
                    uint32_t a = a2png::hgr_addr(base, y, cx);
                    uint8_t bm = dbl ? flat[a] : rail_mmu(computer)->probe_peek(a);
                    uint8_t ba = dbl ? flat[a + 0x10000] : 0;
                    for (int k = 0; k < bpc; k++) {
                        uint8_t src = dbl ? (k < 7 ? ba : bm) : bm;
                        int bit = dbl ? (k % 7) : k;
                        uint8_t v = (src & (1 << bit)) ? 255 : 0;
                        if (v) lit++;
                        int px = cx * bpc + k;
                        for (int sy = 0; sy < syn; sy++)
                            for (int sx = 0; sx < sxn; sx++)
                                img[(size_t)(y * syn + sy) * ow +
                                    (size_t)(px * sxn + sx)] = v;
                    }
                }
            }
            bool ok = a2png::write_gray(fbuf, img.data(), ow, oh);
            snprintf(result, rsz,
                     ok ? "status=OK png profile=bits-mono %s page%d %dx%d scale%d "
                          "lit=%ld -> %s"
                        : "status=FAIL png-write-fail %s page%d %dx%d scale%d lit=%ld %s",
                     dbl ? "DHGR" : "HGR", page, ow, oh, scale, lit, fbuf);
        } else {
            snprintf(result, rsz, "status=FAIL png-parse-fail");
        }
        return true;
    }
    if (!strncmp(line, "pngc ", 5)) {
        char fbuf[512];
        int page = 0, scale = 2;        // 0 = the displayed page; see `png`
        char pbuf[32] = "4dot";
        if (sscanf(line + 5, "%511s %d %d %31s", fbuf, &page, &scale, pbuf) >= 1) {
            if (page == 0) {
                display_state_t *cds = (display_state_t *)computer->cached_display_state;
                VideoScannerII *cvs = cds ? cds->video_scanner : nullptr;
                page = (cvs && cvs->is_page_2()) ? 2 : 1;
            }
            if (page != 2) page = 1;
            if (scale < 1) scale = 1;
            if (scale > 8) scale = 8;
            uint32_t base = (page == 2) ? 0x4000u : 0x2000u;
            const uint8_t *flat = rail_video_base(computer);
            if (!flat) {
                snprintf(result, rsz, "status=FAIL pngc-no-flat-image");
            } else if (!strcmp(pbuf, "mono")) {
                const int W = 560, H = 192;
                const int sxn = scale, syn = scale * 2;
                int ow = W * sxn, oh = H * syn;
                std::vector<uint8_t> img((size_t)ow * oh, 0);
                for (int y = 0; y < H; y++) {
                    for (int cx = 0; cx < 40; cx++) {
                        uint32_t a = a2png::hgr_addr(base, y, cx);
                        uint8_t bm = flat[a];
                        uint8_t ba = flat[a + 0x10000];
                        for (int k = 0; k < 14; k++) {
                            uint8_t src = k < 7 ? ba : bm;
                            int bit = k % 7;
                            uint8_t v = (src & (1 << bit)) ? 255 : 0;
                            int px = cx * 14 + k;
                            for (int sy = 0; sy < syn; sy++)
                                for (int sx = 0; sx < sxn; sx++)
                                    img[(size_t)(y * syn + sy) * ow +
                                        (size_t)(px * sxn + sx)] = v;
                        }
                    }
                }
                bool ok = a2png::write_gray(fbuf, img.data(), ow, oh);
                snprintf(result, rsz,
                         ok ? "status=OK pngc profile=mono page=%d %dx%d -> %s"
                            : "status=FAIL pngc-write-fail %s",
                         page, ow, oh, fbuf);
            } else {
                std::vector<uint8_t> rgb(560 * 192 * 3);
                a2dhgr::render_page_rgb(flat + 0x10000 + base, flat + base, rgb.data(), 1);
                const int sxn = scale, syn = scale * 2;
                int ow = 560 * sxn, oh = 192 * syn;
                std::vector<uint8_t> scaled((size_t)ow * oh * 3);
                for (int y = 0; y < 192; y++) {
                    for (int x = 0; x < 560; x++) {
                        const uint8_t *s = &rgb[((size_t)y * 560 + x) * 3];
                        for (int sy = 0; sy < syn; sy++)
                            for (int sx = 0; sx < sxn; sx++) {
                                uint8_t *d = &scaled[(((size_t)y * syn + sy) * ow +
                                                      (size_t)x * sxn + sx) *
                                                     3];
                                d[0] = s[0];
                                d[1] = s[1];
                                d[2] = s[2];
                            }
                    }
                }
                bool ok = a2png::write_rgb(fbuf, scaled.data(), ow, oh);
                snprintf(result, rsz,
                         ok ? "status=OK pngc profile=4dot page=%d %dx%d -> %s"
                            : "status=FAIL pngc-write-fail %s",
                         page, ow, oh, fbuf);
            }
        } else {
            snprintf(result, rsz, "status=FAIL pngc-parse-fail");
        }
        return true;
    }
    return false;
}


// ---- meta: oracle / help / manifest / rail ---------------------------------
inline bool try_meta(const char *line, char *result, size_t rsz) {
    if (!strcmp(line, "oracle") || !strncmp(line, "oracle ", 7)) {
        snprintf(result, rsz, "%s", a2manifest::oracle_banner());
        return true;
    }
    if (!strcmp(line, "help") || !strncmp(line, "help ", 5)) {
        const char *path = nullptr;
        if (!strncmp(line, "help ", 5) && line[5]) path = line + 5;
        if (path && path[0]) {
            FILE *hf = fopen(path, "wb");
            if (!hf) {
                snprintf(result, rsz, "status=FAIL help-open-fail %s", path);
            } else {
                a2manifest::write_help_short(hf);
                fclose(hf);
                snprintf(result, rsz, "status=OK help wrote %s", path);
            }
        } else {
            a2manifest::format_help_ack(result, rsz);
        }
        return true;
    }
    if (!strncmp(line, "manifest ", 9)) {
        const char *path = line + 9;
        while (*path == ' ') path++;
        if (!*path) {
            snprintf(result, rsz, "status=FAIL manifest-need-file");
        } else {
            FILE *mf = fopen(path, "wb");
            if (!mf) {
                snprintf(result, rsz, "status=FAIL manifest-open-fail %s", path);
            } else {
                a2manifest::write_manifest(mf);
                fclose(mf);
                snprintf(result, rsz, "status=OK manifest wrote %s", path);
            }
        }
        return true;
    }
    if (!strncmp(line, "rail", 4) && (line[4] == 0 || line[4] == ' ')) {
        const char *rest = line[4] ? line + 5 : "";
        while (*rest == ' ') rest++;
        if (!*rest || !strncmp(rest, "list", 4)) {
            a2manifest::format_rail_ack(result, rsz);
        } else if (!strncmp(rest, "env-only", 8)) {
            const char *path = rest + 8;
            while (*path == ' ') path++;
            if (!*path) {
                a2manifest::format_rail_ack(result, rsz);
            } else {
                FILE *rf = fopen(path, "wb");
                if (!rf) {
                    snprintf(result, rsz, "status=FAIL rail-open-fail %s", path);
                } else {
                    a2manifest::write_env_only_rails(rf);
                    fclose(rf);
                    snprintf(result, rsz, "status=OK rail env-only wrote %s", path);
                }
            }
        } else {
            snprintf(result, rsz, "status=FAIL rail-need: list|env-only [file]");
        }
        return true;
    }
    return false;
}

// ---- live L4: valtrap / itrace / tbtrace / callstream ----------------------
inline bool try_trace_break(const char *line, char *result, size_t rsz) {
    if (!strncmp(line, "valtrap", 7) && (line[7] == 0 || line[7] == ' ')) {
        const char *rest = line[7] ? line + 8 : "";
        while (*rest == ' ') rest++;
        if (!*rest || !strncmp(rest, "status", 6)) {
            snprintf(result, rsz,
                     "status=OK valtrap on=%d val=$%X width=%d hits=%d max=%d path=bus_write",
                     g_valtrap_on ? 1 : 0, (unsigned)g_valtrap_val,
                     g_valtrap_width, g_valtrap_hits, g_valtrap_max);
        } else if (!strncmp(rest, "clear", 5) || !strncmp(rest, "off", 3)) {
            g_valtrap_on = false;
            g_valtrap_hits = 0;
            snprintf(result, rsz, "status=OK valtrap cleared");
        } else if (!strncmp(rest, "set ", 4)) {
            const char *spec = rest + 4;
            while (*spec == ' ') spec++;
            char *ep = nullptr;
            unsigned long v = strtoul(spec, &ep, 16);
            int width = 3;
            if (ep && *ep == ':') width = atoi(ep + 1);
            if (width < 1) width = 1;
            if (width > 4) width = 4;
            g_valtrap_val = (uint32_t)v;
            g_valtrap_width = width;
            g_valtrap_hits = 0;
            g_valtrap_on = true;
            for (int i = 0; i < 8; i++) {
                g_valtrap_ra[i] = 0;
                g_valtrap_rd[i] = 0;
            }
            g_valtrap_ri = 0;
            snprintf(result, rsz,
                     "status=OK valtrap LIVE val=$%lX width=%d path=bus_write", v, width);
        } else {
            snprintf(result, rsz, "status=FAIL valtrap-need: set <hex>[:w]|clear|status");
        }
        return true;
    }
    if (!strncmp(line, "itrace", 6) && (line[6] == 0 || line[6] == ' ')) {
        const char *rest = line[6] ? line + 7 : "";
        while (*rest == ' ') rest++;
        if (!*rest || !strncmp(rest, "status", 6)) {
            snprintf(result, rsz,
                     "status=OK itrace on=%d armed=%d from=$%06X n=%d logged=%d path=execute",
                     g_iigs_itrace_enabled ? 1 : 0, g_iigs_itrace_armed ? 1 : 0,
                     (unsigned)g_iigs_itrace_from, g_iigs_itrace_n, g_iigs_itrace_logged);
        } else if (!strncmp(rest, "clear", 5) || !strncmp(rest, "off", 3)) {
            g_iigs_itrace_enabled = false;
            g_iigs_itrace_armed = false;
            g_iigs_itrace_use_pc = false;
            g_iigs_itrace_logged = 0;
            snprintf(result, rsz, "status=OK itrace cleared");
        } else if (!strncmp(rest, "now", 3)) {
            g_iigs_itrace_enabled = true;
            g_iigs_itrace_armed = true;
            g_iigs_itrace_use_pc = false;
            g_iigs_itrace_logged = 0;
            snprintf(result, rsz, "status=OK itrace LIVE armed now n=%d path=execute",
                     g_iigs_itrace_n);
        } else if (!strncmp(rest, "from ", 5)) {
            unsigned long pc = strtoul(rest + 5, nullptr, 16);
            g_iigs_itrace_from = (uint32_t)pc & 0xFFFFFF;
            g_iigs_itrace_use_pc = true;
            g_iigs_itrace_enabled = true;
            g_iigs_itrace_armed = false;
            g_iigs_itrace_logged = 0;
            snprintf(result, rsz, "status=OK itrace LIVE from=$%06lX n=%d path=execute",
                     pc & 0xFFFFFF, g_iigs_itrace_n);
        } else if (!strncmp(rest, "n ", 2)) {
            int v = atoi(rest + 2);
            if (v > 0) g_iigs_itrace_n = v;
            snprintf(result, rsz, "status=OK itrace n=%d", g_iigs_itrace_n);
        } else {
            snprintf(result, rsz,
                     "status=FAIL itrace-need: from <pc>|now|n <count>|clear|status");
        }
        return true;
    }
    if (!strncmp(line, "tbtrace", 7) && (line[7] == 0 || line[7] == ' ')) {
        const char *rest = line[7] ? line + 8 : "";
        while (*rest == ' ') rest++;
        if (!*rest || !strncmp(rest, "status", 6)) {
            snprintf(result, rsz, "status=OK tbtrace on=%d bank=%d path=tool_locator",
                     g_iigs_tbtrace_enabled ? 1 : 0, g_iigs_tbtrace_bank);
        } else if (!strncmp(rest, "on", 2)) {
            g_iigs_tbtrace_enabled = true;
            snprintf(result, rsz, "status=OK tbtrace LIVE on bank=%d", g_iigs_tbtrace_bank);
        } else if (!strncmp(rest, "off", 3)) {
            g_iigs_tbtrace_enabled = false;
            snprintf(result, rsz, "status=OK tbtrace off");
        } else if (!strncmp(rest, "bank ", 5)) {
            const char *b = rest + 5;
            while (*b == ' ') b++;
            if (!strncmp(b, "all", 3))
                g_iigs_tbtrace_bank = -1;
            else
                g_iigs_tbtrace_bank = (int)strtol(b, nullptr, 16);
            snprintf(result, rsz, "status=OK tbtrace bank=%d", g_iigs_tbtrace_bank);
        } else {
            snprintf(result, rsz,
                     "status=FAIL tbtrace-need: on|off|status|bank <hex>|bank all");
        }
        return true;
    }
    if (!strncmp(line, "callstream", 10) && (line[10] == 0 || line[10] == ' ')) {
        // LIVE L4: NDJSON toolbox/GSOS call stream (A2GSPU_CALLSTREAM).
        //   callstream on <file> | off | status
        const char *rest = line[10] ? line + 11 : "";
        while (*rest == ' ') rest++;
        if (!*rest || !strncmp(rest, "status", 6)) {
            snprintf(result, rsz, "status=OK callstream on=%d seq=%d path=tool_locator",
                     g_callstream_on ? 1 : 0, g_callstream_seq);
        } else if (!strncmp(rest, "off", 3) || !strncmp(rest, "clear", 5)) {
            if (g_callstream_out) {
                fclose(g_callstream_out);
                g_callstream_out = nullptr;
            }
            g_callstream_on = false;
            snprintf(result, rsz, "status=OK callstream off");
        } else if (!strncmp(rest, "on ", 3)) {
            const char *path = rest + 3;
            while (*path == ' ') path++;
            if (!*path) {
                snprintf(result, rsz, "status=FAIL callstream-need-file");
            } else {
                if (g_callstream_out) {
                    fclose(g_callstream_out);
                    g_callstream_out = nullptr;
                }
                g_callstream_out = fopen(path, "wb");
                g_callstream_on = (g_callstream_out != nullptr);
                g_callstream_seq = 0;
                snprintf(result, rsz,
                         g_callstream_on
                             ? "status=OK callstream LIVE file=%s path=tool_locator"
                             : "status=FAIL callstream-open-fail %s",
                         path);
            }
        } else {
            snprintf(result, rsz, "status=FAIL callstream-need: on <file>|off|status");
        }
        return true;
    }
    return false;
}

// ---- assert + DHGR calibrate/export/golden ---------------------------------
inline bool try_assert_dhgr(const char *line, char *result, size_t rsz,
                            computer_t *computer) {
    if (!strncmp(line, "assert ", 7)) {
        const char *p = line + 7;
        int nfail = 0, npass = 0;
        char detail[600] = {0};
        size_t dlen = 0;
        while (*p) {
            while (*p == ' ' || *p == ';') p++;
            if (!*p) break;
            const char *start = p;
            while (*p && *p != ';') p++;
            char tok[128];
            size_t tl = (size_t)(p - start);
            if (tl >= sizeof tok) tl = sizeof tok - 1;
            memcpy(tok, start, tl);
            tok[tl] = 0;
            while (tl > 0 && tok[tl - 1] == ' ') tok[--tl] = 0;
            unsigned bank = 0, addr = 0, want = 0;
            uint32_t full = 0;
            bool ok_parse = false;
            if (sscanf(tok, "peek:%x:%x==%x", &bank, &addr, &want) == 3) {
                full = ((bank & 0xFF) << 16) | (addr & 0xFFFF);
                ok_parse = true;
            } else if (sscanf(tok, "peek:%x==%x", &addr, &want) == 2) {
                full = addr & 0xFFFFFF;
                ok_parse = true;
            }
            if (!ok_parse) {
                nfail++;
                if (dlen + 40 < sizeof detail)
                    dlen += (size_t)snprintf(detail + dlen, sizeof detail - dlen,
                                             " parse-fail");
                continue;
            }
            uint8_t got = rail_mmu(computer) ? rail_mmu(computer)->probe_peek(full) : (uint8_t)0xFF;
            if (got == (uint8_t)(want & 0xFF)) {
                npass++;
            } else {
                nfail++;
                if (dlen + 48 < sizeof detail)
                    dlen += (size_t)snprintf(
                        detail + dlen, sizeof detail - dlen,
                        " FAIL peek:%06X got=%02X want=%02X", (unsigned)full,
                        (unsigned)got, (unsigned)(want & 0xFF));
            }
        }
        snprintf(result, rsz, "status=%s assert pass=%d fail=%d path=probe_peek%s",
                 nfail ? "FAIL" : "PASS", npass, nfail, detail);
        return true;
    }
    if (!strncmp(line, "dhgr-calibrate", 14)) {
        int fails = a2dhgr::calibrate_solid_roundtrip();
        snprintf(result, rsz,
                 fails == 0 ? "status=PASS dhgr-calibrate (16/16 solids)"
                            : "status=FAIL dhgr-calibrate (%d colours)",
                 fails);
        return true;
    }
    if (!strncmp(line, "dhgr-export ", 12)) {
        char dbuf[512];
        if (sscanf(line + 12, "%511s", dbuf) == 1) {
            setupConfig();
            generate_filters(NUM_TAPS);
            init_hgr_LUT();
            char p4[600], pn[600];
            snprintf(p4, sizeof p4, "%s/gssquared_4dot.bin", dbuf);
            snprintf(pn, sizeof pn, "%s/gssquared_ntsc.bin", dbuf);
            bool ok4 = a2dhgr::export_4dot_bin(p4);
            bool okn = a2dhgr::export_ntsc_lut_bin(pn);
            snprintf(result, rsz, "status=%s dhgr-export 4dot=%s ntsc=%s -> %s",
                     (ok4 && okn) ? "OK" : "FAIL", ok4 ? "ok" : "FAIL",
                     okn ? "ok" : "FAIL", dbuf);
        } else {
            snprintf(result, rsz, "status=FAIL dhgr-export-parse-fail");
        }
        return true;
    }
    if (!strncmp(line, "dhgr-golden ", 12)) {
        // dhgr-golden <file> [page] [vram-raw|4dot] [bless]
        // Profiles: vram-raw (16K AUX‖MAIN FNV) | 4dot (discrete RGB FNV).
        char fbuf[512] = {0};
        int page = 1;
        bool bless = false;
        a2dhgr::GoldenProfile prof = a2dhgr::GoldenProfile::VramRaw;
        char t1[64] = {0}, t2[64] = {0}, t3[64] = {0};
        int narg = sscanf(line + 12, "%511s %63s %63s %63s", fbuf, t1, t2, t3);
        if (narg < 1 || !fbuf[0]) {
            snprintf(result, rsz, "status=FAIL dhgr-golden-parse-fail");
            return true;
        }
        auto take_arg = [&](const char *a) {
            if (!a || !a[0]) return;
            if (!strcmp(a, "bless")) {
                bless = true;
                return;
            }
            a2dhgr::GoldenProfile ptmp;
            if (a2dhgr::parse_golden_profile(a, &ptmp)) {
                prof = ptmp;
                return;
            }
            int pg = atoi(a);
            if (pg == 1 || pg == 2) page = pg;
        };
        if (narg >= 2) take_arg(t1);
        if (narg >= 3) take_arg(t2);
        if (narg >= 4) take_arg(t3);
        if (page != 2) page = 1;
        uint32_t base = (page == 2) ? 0x4000u : 0x2000u;
        const uint8_t *flat = rail_video_base(computer);
        if (!flat) {
            snprintf(result, rsz, "status=FAIL dhgr-golden-no-flat");
            return true;
        }
        const char *pname = a2dhgr::golden_profile_name(prof);
        uint64_t h = a2dhgr::page_hash(flat + 0x10000 + base, flat + base, prof);
        unsigned long long old = 0;
        FILE *gf = fopen(fbuf, "rb");
        bool missing = (gf == nullptr);
        if (gf) {
            if (fscanf(gf, "%llx", &old) != 1) missing = true;
            fclose(gf);
        }
        if (bless || missing) {
            FILE *wf = fopen(fbuf, "wb");
            if (!wf) {
                snprintf(result, rsz, "status=FAIL dhgr-golden-write-fail %s", fbuf);
            } else {
                fprintf(wf, "%016llX\n", (unsigned long long)h);
                fclose(wf);
                snprintf(result, rsz,
                         "status=PASS dhgr-golden BLESSED profile=%s page=%d "
                         "hash=%016llX file=%s",
                         pname, page, (unsigned long long)h, fbuf);
            }
        } else if ((uint64_t)old == h) {
            snprintf(result, rsz,
                     "status=PASS dhgr-golden MATCH profile=%s page=%d hash=%016llX",
                     pname, page, (unsigned long long)h);
        } else {
            snprintf(result, rsz,
                     "status=FAIL dhgr-golden DIFF profile=%s page=%d "
                     "got=%016llX want=%016llX",
                     pname, page, (unsigned long long)h, old);
        }
        return true;
    }
    return false;
}

// ---- instruction-granular step helpers (CTRL gaps #3/#4/#5) ----------------
// execute_next() no-ops while reset_asserted / clock_stopped; CTRL replaces the
// frame path that would clear them, so arm before direct step/run-until.
inline const char *arm_cpu(computer_t *computer) {
    cpu_state *cpu = computer->cpu;
    const char *note = nullptr;
    if (cpu->reset_asserted) { cpu->reset_asserted = 0; note = " [cleared RESET]"; }
    if (cpu->clock_stopped)  {
        cpu->clock_stopped = false;
        note = note ? " [cleared RESET+STOP]" : " [cleared STOP]";
    }
    return note;
}

inline void step_one(computer_t *computer) {
    cpu_state *cpu = computer->cpu;
    NClock *clock = computer->clock;
    if (computer->event_timer->isEventPassed(clock->get_c14m()))
        computer->event_timer->processEvents(clock->get_c14m());
    if (computer->vid_event_timer->isEventPassed(clock->get_vid_cycles()))
        computer->vid_event_timer->processEvents(clock->get_vid_cycles());
    if (computer->cpu_event_timer->isEventPassed(clock->get_cycles()))
        computer->cpu_event_timer->processEvents(clock->get_cycles());
    (cpu->cpun->execute_next)(cpu);
    // Advance frame_end when step races past it so subsequent `run` is not a no-op.
    if (clock->get_c14m() >= clock->get_frame_end_c14M()) {
        clock->next_frame();
        computer->last_start_frame_c14m = clock->get_frame_start_c14M();
    }
}

// Shared CPU-state line for step / run-until (and optional cpu verb).
// Keyboard latch from MODULE, never probe_peek($C000) (filler) or read (consumes).
inline void format_cpu_line(computer_t *computer, char *out, size_t outsz) {
    cpu_state *c = computer->cpu;
    keyboard_state_t *kb =
        (keyboard_state_t *)computer->get_module_state(MODULE_KEYBOARD);
    int akd = kb ? kb->key_down_count : -1;
    uint8_t kbd = kb ? kb->kb_key_strobe
                     : (rail_mmu(computer) ? rail_mmu(computer)->probe_peek(0xC000) : 0);
    // SHOW THE REGISTERS THE CODE IS ACTUALLY USING.
    //
    // This printed A/X/Y masked to 8 bits and never showed D or the data bank at
    // all, which on a 65816 in native mode means the one instrument for looking
    // at the CPU cannot show the CPU. After `LDA #$1234` it reported `A=34`, and
    // that ambiguity is not academic: it cost a real detour here, because "the
    // accumulator is 8-bit" and "the display is truncated" look identical, and
    // the first is a catastrophic emulator bug while the second is cosmetic.
    //
    // Width follows the machine: 16-bit only when native AND the relevant width
    // flag is clear. Emulation mode is byte-for-byte unchanged, so anything
    // parsing the old format keeps working.
    //
    // GATED ON THE PROCESSOR, NOT ON E. The first version tested `E == 0`, which
    // is true on a 6502 and a 65C02 as well -- those parts have no E flag at all,
    // so the field simply reads zero. Platform 3 immediately started reporting
    // `A=0000 ... D=0000 DBR=00 MX=00` on a 65C02: four registers that do not
    // exist, printed as though they held state. Caught by railcheck on the very
    // next run, which is the second time this session a regression suite has
    // caught something the change itself looked obviously correct.
    const bool is816 = (c->cpu_type == PROCESSOR_65816);
    const bool nat  = is816 && (c->E & 1) == 0;
    const bool a16  = nat && !c->_M;
    const bool i16  = nat && !c->_X;
    char abuf[8], xbuf[8], ybuf[8];
    if (a16) snprintf(abuf, sizeof abuf, "%04X", (unsigned)(c->a & 0xFFFF));
    else     snprintf(abuf, sizeof abuf, "%02X", (unsigned)(c->a & 0xFF));
    if (i16) { snprintf(xbuf, sizeof xbuf, "%04X", (unsigned)(c->x & 0xFFFF));
               snprintf(ybuf, sizeof ybuf, "%04X", (unsigned)(c->y & 0xFFFF)); }
    else     { snprintf(xbuf, sizeof xbuf, "%02X", (unsigned)(c->x & 0xFF));
               snprintf(ybuf, sizeof ybuf, "%02X", (unsigned)(c->y & 0xFF)); }

    // D and DBR only in native mode: on a 6502/65C02 they do not exist, and
    // printing a permanent "D=0000 DBR=00" there is noise that reads as state.
    char bank[32]; bank[0] = 0;
    if (nat) snprintf(bank, sizeof bank, " D=%04X DBR=%02X MX=%d%d",
                      (unsigned)(c->d & 0xFFFF), (unsigned)(c->db & 0xFF),
                      (int)(c->_M & 1), (int)(c->_X & 1));

    snprintf(out, outsz,
        "PC=%02X:%04X A=%s X=%s Y=%s SP=%04X%s P=%02X E=%d HALT=%d STP=%d RDY=%d KBD=%02X AKD=%d",
        (unsigned)((c->full_pc >> 16) & 0xFF), (unsigned)(c->full_pc & 0xFFFF),
        abuf, xbuf, ybuf,
        (unsigned)(c->sp & 0xFFFF), bank, (unsigned)(c->p & 0xFF),
        (int)(c->E & 1), (int)(c->halt ? 1 : 0), (int)(c->clock_stopped ? 1 : 0),
        (int)(c->rdy ? 1 : 0), (unsigned)kbd, akd);
}

// A fired breakpoint (or save-at) leaves cpu->halt == HLT_USER, and
// run_one_frame's top-of-frame guard then refuses to advance -- so every
// subsequent `run` answered "status=HALT ran=0 cycles=0" forever, and the only
// escape on the whole rail was `reset`, which discards the very state you
// stopped to look at. An "interactive breakpoint" you cannot continue from is a
// one-way door, and a silent one: the ack said HALT without saying how to leave.
//
// An explicit run/step/run-until IS the intent to continue, so clear a user halt
// here and SAY SO in the ack. Never clear HLT_INSTRUCTION: that is the guest CPU
// genuinely jammed on a halting opcode, a real machine state the agent has to be
// able to see rather than have papered over.
inline bool rail_clear_user_halt(computer_t *computer) {
    if (!computer->cpu || computer->cpu->halt != HLT_USER) return false;
    computer->cpu->halt = 0;
    return true;
}

// run / step / run-until — needs ctrl_frame for itrace frame clock on `run`.
inline bool try_exec(const char *line, char *result, size_t rsz,
                     computer_t *computer, int *ctrl_frame) {
    if (!strncmp(line, "run ", 4)) {
        int frames = atoi(line + 4);
        const char *rsm = rail_clear_user_halt(computer) ? " resumed-from-halt" : "";
        // `step` and `run-until` have always armed the CPU here; `run` did not,
        // and that asymmetry made the most-used verb on the rail lie. On a fresh
        // IIe session reset_asserted is still set, execute_next() no-ops on it,
        // and the frame path under CTRL is not the one that would clear it -- so
        // `run 2` advanced the clock 34056 cycles, executed ZERO instructions,
        // left PC untouched, and answered "status=OK ran=2". The existing
        // RAN-NOTHING guard could not catch it because it keys off elapsed
        // cycles, and the cycles were real; only the instructions were missing.
        // (Platform 5 masked it: the IIgs comes up without reset asserted, so
        // the same script worked there and the IIe looked like a content bug.)
        const char *armed = arm_cpu(computer);
        uint64_t cyc0 = computer->clock->get_cycles();
        uint32_t pc0  = computer->cpu->full_pc & 0xFFFFFF;
        int ran = 0;
        bool halted = false;
        for (int i = 0; i < frames; i++) {
            if (ctrl_frame) iigs_itrace_frame_tick((*ctrl_frame)++);
            if (!run_one_frame(computer)) { halted = true; break; }
            ran++;
        }
        uint64_t dc = computer->clock->get_cycles() - cyc0;
        uint32_t pc1 = computer->cpu->full_pc & 0xFFFFFF;
        if (halted) {
            snprintf(result, rsz,
                     "status=HALT ran=%d cycles=%llu (in-command)%s%s halt=%d "
                     "-- `resume` (or the next run/step) continues past a breakpoint",
                     ran, (unsigned long long)dc, armed ? armed : "", rsm,
                     (int)computer->cpu->halt);
        } else if (dc == 0) {
            snprintf(result, rsz,
                     "status=FAIL RAN NOTHING: %d frame(s), 0 cycles, PC still $%04X "
                     "-- exec_mode=%d clock_mode=%d instr_left=%d halt=%d",
                     ran, (unsigned)(pc1 & 0xFFFF),
                     (int)computer->execution_mode,
                     (int)(computer->clock ? computer->clock->get_clock_mode() : -1),
                     (int)computer->instructions_left,
                     (int)computer->cpu->halt);
        } else {
            snprintf(result, rsz,
                     "status=OK ran=%d cycles=%llu (in-command) PC $%04X->$%04X%s%s",
                     ran, (unsigned long long)dc,
                     (unsigned)(pc0 & 0xFFFF), (unsigned)(pc1 & 0xFFFF),
                     armed ? armed : "", rsm);
        }
        soft_watch_after(computer, result, rsz);
        return true;
    }
    if (!strncmp(line, "run-until ", 10)) {
        char addrbuf[64] = {0};
        long budget = 2000000;
        uint32_t target = 0;
        if (sscanf(line + 10, "%63s %ld", addrbuf, &budget) >= 1 &&
            parse_addr(addrbuf, &target)) {
            const char *armed = arm_cpu(computer);
            const char *rsm = rail_clear_user_halt(computer) ? " resumed-from-halt" : "";
            uint64_t cyc0 = computer->clock ? computer->clock->get_cycles() : 0;
            long i = 0; bool hit = false;
            for (; i < budget; i++) {
                if (computer->cpu->halt) break;
                step_one(computer);
                if ((computer->cpu->full_pc & 0xFFFFFF) == target) { hit = true; break; }
            }
            uint64_t dcyc = (computer->clock ? computer->clock->get_cycles() : 0) - cyc0;
            char st[192];
            format_cpu_line(computer, st, sizeof st);
            snprintf(result, rsz,
                     "status=%s instr=%ld cycles=%llu (in-command)%s%s %s",
                     hit ? "OK" : (computer->cpu->halt ? "HALT" : "BUDGET"),
                     i, (unsigned long long)dcyc, armed ? armed : "", rsm, st);
            soft_watch_after(computer, result, rsz);
        } else {
            snprintf(result, rsz, "status=FAIL run-until-parse-fail");
        }
        return true;
    }
    // "step" or "step N" — not "stepper" if we require end/space, but match legacy
    // strncmp(line,"step",4) which accepts any prefix of length>=4 starting step.
    if (!strncmp(line, "step", 4) && (line[4] == 0 || line[4] == ' ')) {
        int n = 1;
        if (line[4] == ' ') n = atoi(line + 5);
        if (n < 1) n = 1;
        const char *armed = arm_cpu(computer);
        const char *rsm = rail_clear_user_halt(computer) ? " resumed-from-halt" : "";
        uint64_t cyc0 = computer->clock ? computer->clock->get_cycles() : 0;
        int done = 0;
        for (; done < n; done++) {
            if (computer->cpu->halt) break;
            step_one(computer);
        }
        uint64_t dcyc = (computer->clock ? computer->clock->get_cycles() : 0) - cyc0;
        char st[192];
        format_cpu_line(computer, st, sizeof st);
        snprintf(result, rsz,
                 "status=OK stepped=%d cycles=%llu (in-command)%s%s %s",
                 done, (unsigned long long)dcyc, armed ? armed : "", rsm, st);
        soft_watch_after(computer, result, rsz);
        return true;
    }
    // resume — the explicit half of the breakpoint round trip. Distinguishes the
    // two halts by name, because they need opposite responses: a user halt is
    // continuable, a jammed CPU is not and no amount of `run` will help.
    if (!strcmp(line, "resume")) {
        const int h = computer->cpu ? computer->cpu->halt : 0;
        if (h == HLT_USER) {
            computer->cpu->halt = 0;
            char st[192];
            format_cpu_line(computer, st, sizeof st);
            snprintf(result, rsz, "status=OK resume cleared user-halt %s", st);
        } else if (h == HLT_INSTRUCTION) {
            snprintf(result, rsz, "status=FAIL resume-cpu-jammed halt=%d -- the guest "
                     "executed a halting instruction; only `reset` leaves this state", h);
        } else if (h) {
            snprintf(result, rsz, "status=FAIL resume-unknown-halt halt=%d", h);
        } else {
            snprintf(result, rsz, "status=OK resume not-halted (nothing to clear)");
        }
        return true;
    }
    return false;
}

// keys / press / key / holdkey
inline bool try_input(const char *line, char *result, size_t rsz,
                      computer_t *computer) {
    if (!strncmp(line, "keys ", 5)) {
        keyboard_state_t *kb =
            (keyboard_state_t *)computer->get_module_state(MODULE_KEYBOARD);
        if (kb) kb->paste_buffer += (line + 5);
        else snprintf(result, rsz, "status=FAIL no-keyboard");
        return true;
    }
    /* devstate [name|all [file]] -- the per-device state the emulator already
       computes, which an agent previously could not reach at all.

       Every substantial device registers a debug_display handler: the ADB
       microcontroller's registers and per-device SRQ bits, the IWM and Disk II
       head and motor state, the mouse position and clamp window, the Ensoniq
       oscillators, the game controller, the IIe memory map, the keyboard. The
       emulator builds all of it on demand -- and the only consumer was an
       on-screen overlay for a human. Over the rail it was invisible.

       That is a black box of the most annoying kind: the information exists,
       is correct, is formatted, and is unreachable by the one caller that
       cannot look at the screen.

         devstate            list the handlers this machine registered
         devstate <name>     that handler's lines, inline in the ack
         devstate all <file> every handler, written out (the ack has a size cap) */
    if (!strncmp(line, "devstate", 8) && (line[8] == 0 || line[8] == ' ')) {
        const char *arg = (line[8] == ' ') ? line + 9 : "";
        while (*arg == ' ') arg++;

        if (!*arg) {
            size_t off = 0;
            int m = snprintf(result, rsz, "status=OK devstate handlers=%zu:",
                             computer->debug_display_handlers.size());
            if (m > 0) off = (size_t)m;
            for (auto &h : computer->debug_display_handlers) {
                if (off + h.name.size() + 2 >= rsz) break;
                m = snprintf(result + off, rsz - off, " %s", h.name.c_str());
                if (m > 0) off += (size_t)m;
            }
            return true;
        }

        // `all [file]` -- everything, because a caller diffing machine state
        // wants one artifact rather than N round trips.
        if (!strncmp(arg, "all", 3)) {
            const char *path = arg + 3;
            while (*path == ' ') path++;
            if (!*path) {
                snprintf(result, rsz, "status=FAIL devstate-all-needs-a-file "
                                      "(usage: devstate all <file>)");
                return true;
            }
            FILE *f = fopen(path, "w");
            if (!f) {
                snprintf(result, rsz, "status=FAIL devstate-open-fail %s", path);
                return true;
            }
            int nh = 0, nl = 0;
            for (auto &h : computer->debug_display_handlers) {
                DebugFormatter *df = h.handler ? h.handler() : nullptr;
                if (!df) continue;
                fprintf(f, "## %s\n", h.name.c_str());
                for (const auto &ln : df->getLines()) { fprintf(f, "%s\n", ln.c_str()); nl++; }
                fprintf(f, "\n");
                delete df;
                nh++;
            }
            fclose(f);
            snprintf(result, rsz, "status=OK devstate all handlers=%d lines=%d -> %s",
                     nh, nl, path);
            return true;
        }

        DebugFormatter *df = computer->call_debug_display_handler(std::string(arg));
        if (!df) {
            size_t off = 0;
            int m = snprintf(result, rsz,
                             "status=FAIL devstate-no-such-handler '%s'. known:", arg);
            if (m > 0) off = (size_t)m;
            for (auto &h : computer->debug_display_handlers) {
                if (off + h.name.size() + 2 >= rsz) break;
                m = snprintf(result + off, rsz - off, " %s", h.name.c_str());
                if (m > 0) off += (size_t)m;
            }
            return true;
        }
        size_t off = 0;
        int m = snprintf(result, rsz, "status=OK devstate %s |", arg);
        if (m > 0) off = (size_t)m;
        for (const auto &ln : df->getLines()) {
            if (off + ln.size() + 4 >= rsz) {
                snprintf(result + off, rsz - off, " ...(truncated; devstate all <file>)");
                break;
            }
            m = snprintf(result + off, rsz - off, " %s |", ln.c_str());
            if (m > 0) off += (size_t)m;
        }
        delete df;
        return true;
    }

    /* speaker -- how many times has $C030 been toggled, and when was the last?

       Every Apple II sound is made by toggling the speaker at the right
       moments, and those toggles went straight into an audio event buffer that
       only the audio device ever saw. From outside, a working speaker and a
       dead one looked identical unless you listened. This reports the count and
       the c14m timestamp of the most recent toggle, so a harness can check both
       that the accesses arrive and that they are stamped on the video clock the
       audio path resamples against -- which is what makes the PITCH right,
       rather than merely making sound happen. */
    if (!strncmp(line, "speaker", 7) && (line[7] == 0 || line[7] == ' ')) {
        speaker_state_t *sp = (speaker_state_t *)computer->get_module_state(MODULE_SPEAKER);
        if (!sp) {
            snprintf(result, rsz, "status=FAIL no-speaker");
            return true;
        }
        snprintf(result, rsz, "status=OK speaker toggles=%llu last_c14m=%llu",
                 (unsigned long long)sp->toggle_count,
                 (unsigned long long)sp->last_toggle_c14m);
        return true;
    }

    /* paddle <n> <0..255>   -- set analogue paddle n and enable injection
       paddle off            -- hand control back to the host mouse/gamepad

       The game controller previously took its input ONLY from live SDL, so on a
       headless rail session there was no way to set a paddle or press a button:
       the one subsystem on the machine no instrument could reach. An injected
       0..255 means what a real ADC reading of 0..255 means -- the strobe seeds
       the decay timer with DECAY * value / 255 -- so the emulated timing is the
       hardware's, not a shortcut around it. */
    /* joymode -- which controller shape the $C061-$C063 switches present.

       The mode was reachable ONLY from a host GUI menu (MENU_CONTROLLER_GAMEPAD
       -> set_joystick_mode), so on a headless rail session two of the three
       modes could not be entered at all -- and the Joyport suspend window,
       which only exists in Atari mode, could therefore never be measured. Same
       shape of hole as the paddle injection above: a real behaviour with no
       instrument that could reach it.

         joymode                 which mode, and the suspend window in cycles
         joymode gamepad         Apple II gamepad/paddles (the default)
         joymode mouse           Apple Mouse as a paddle pair
         joymode atari           Atari-style Joyport: reversed polarity, and
                                 the mux stays suspended for a window after
                                 reset because a real one trips the ROM's
                                 button self-test coming out of it            */
    if (!strncmp(line, "joymode", 7) && (line[7] == 0 || line[7] == ' ')) {
        gamec_state_t *gc = (gamec_state_t *)computer->get_module_state(MODULE_GAMECONTROLLER);
        if (!gc) {
            snprintf(result, rsz, "status=FAIL no-game-controller");
            return true;
        }
        const char *arg = (line[7] == ' ') ? line + 8 : "";
        while (*arg == ' ') arg++;
        if      (!strcmp(arg, "gamepad")) gc->joystick_mode = JOYSTICK_APPLE_GAMEPAD;
        else if (!strcmp(arg, "mouse"))   gc->joystick_mode = JOYSTICK_APPLE_MOUSE;
        else if (!strcmp(arg, "atari"))   gc->joystick_mode = JOYSTICK_ATARI_DPAD;
        else if (*arg && strcmp(arg, "status")) {
            snprintf(result, rsz, "status=FAIL joymode-need: [status]|gamepad|mouse|atari");
            return true;
        }
        const char *nm = gc->joystick_mode == JOYSTICK_ATARI_DPAD   ? "atari"
                       : gc->joystick_mode == JOYSTICK_APPLE_MOUSE  ? "mouse"
                                                                    : "gamepad";
        // suspended= is the question a gate actually asks: not "how long is the
        // window" but "are we still inside it right now".
        const uint64_t now = computer->clock->get_cycles();
        const uint64_t ends = computer->last_reset + gc->joyport_suspend_cycles;
        snprintf(result, rsz,
                 "status=OK joymode %s suspend_cycles=%llu last_reset=%llu now=%llu suspended=%d",
                 nm,
                 (unsigned long long)gc->joyport_suspend_cycles,
                 (unsigned long long)computer->last_reset,
                 (unsigned long long)now,
                 (gc->joystick_mode == JOYSTICK_ATARI_DPAD && now <= ends) ? 1 : 0);
        return true;
    }
    if (!strncmp(line, "paddle ", 7)) {
        gamec_state_t *gc = (gamec_state_t *)computer->get_module_state(MODULE_GAMECONTROLLER);
        if (!gc) {
            snprintf(result, rsz, "status=FAIL no-game-controller");
            return true;
        }
        if (!strncmp(line + 7, "off", 3)) {
            gc->inject_active = false;
            snprintf(result, rsz, "status=OK paddle injection off (host device back in control)");
            return true;
        }
        unsigned n = 0, v = 0;
        if (sscanf(line + 7, "%u %u", &n, &v) == 2 && n < 4 && v < 256) {
            gc->inject_paddle[n] = (uint8_t)v;
            gc->inject_active = true;
            snprintf(result, rsz, "status=OK paddle %u=%u (injection on; PDL0..3 = %u %u %u %u)",
                     n, v, gc->inject_paddle[0], gc->inject_paddle[1],
                     gc->inject_paddle[2], gc->inject_paddle[3]);
        } else {
            snprintf(result, rsz, "status=FAIL paddle-parse (want: paddle <0-3> <0-255> | paddle off)");
        }
        return true;
    }

    /* pbutton <n> <0|1> -- set game switch n (0..2), the PB0-PB2 buttons. */
    if (!strncmp(line, "pbutton ", 8)) {
        gamec_state_t *gc = (gamec_state_t *)computer->get_module_state(MODULE_GAMECONTROLLER);
        if (!gc) {
            snprintf(result, rsz, "status=FAIL no-game-controller");
            return true;
        }
        unsigned n = 0, v = 0;
        if (sscanf(line + 8, "%u %u", &n, &v) == 2 && n < 3 && v < 2) {
            gc->inject_button[n] = (uint8_t)v;
            gc->inject_active = true;
            snprintf(result, rsz, "status=OK pbutton %u=%u (injection on; PB0..2 = %u %u %u)",
                     n, v, gc->inject_button[0], gc->inject_button[1], gc->inject_button[2]);
        } else {
            snprintf(result, rsz, "status=FAIL pbutton-parse (want: pbutton <0-2> <0|1>)");
        }
        return true;
    }

    if (!strncmp(line, "press ", 6)) {
        unsigned int ch = 0; int hold = 15;
        if (sscanf(line + 6, "%x %d", &ch, &hold) >= 1) {
            keyboard_state_t *kb =
                (keyboard_state_t *)computer->get_module_state(MODULE_KEYBOARD);
            keygloo_state_t *kg =
                (keygloo_state_t *)computer->get_module_state(MODULE_KEYGLOO);
            if (kb) {
                kb->kb_key_strobe = (uint8_t)(ch | 0x80);
                if (kb->mk) kb->mk->last_key_val = (uint8_t)ch;
                kb->key_down_count++;
                for (int i = 0; i < hold; i++) {
                    if (!run_one_frame(computer)) {
                        snprintf(result, rsz, "halted@%d", i);
                        break;
                    }
                }
                kb->key_down_count--;
            } else if (kg && kg->kg) {
                kg->kg->force_key((uint8_t)ch);
                keygloo_update_interrupt_status(kg, kg->kg);
                int hk = hold < 3 ? hold : 3;
                kg->kg->hold_key((uint8_t)ch);
                for (int i = 0; i < hold; i++) {
                    if (i == hk) kg->kg->hold_key(0);
                    if (!run_one_frame(computer)) {
                        snprintf(result, rsz, "halted@%d", i);
                        break;
                    }
                }
                kg->kg->hold_key(0);
                kg->kg->key_up();
            } else {
                snprintf(result, rsz, "status=FAIL no-keyboard");
            }
        } else {
            snprintf(result, rsz, "status=FAIL press-parse-fail");
        }
        return true;
    }
    if (!strncmp(line, "key ", 4)) {
        unsigned int ch = 0; int maxf = 120;
        if (sscanf(line + 4, "%x %d", &ch, &maxf) >= 1) {
            keyboard_state_t *kb =
                (keyboard_state_t *)computer->get_module_state(MODULE_KEYBOARD);
            if (!kb) {
                /* status=FAIL, which this did not say. It is a genuine
                   failure -- the key never reaches the guest -- but it announced
                   itself as bare prose, so a caller testing for FAIL saw none and
                   carried on believing the keystroke had landed. Silent failure
                   dressed as a message is worse than either. */
                snprintf(result, rsz,
                         "status=FAIL key-unsupported-on-this-machine "
                         "(no MODULE_KEYBOARD; this machine routes the keyboard "
                         "through the ADB microcontroller -- use 'press' instead)");
            } else {
                if (maxf < 1) maxf = 1;
                kb->kb_key_strobe = (uint8_t)(ch | 0x80);
                if (kb->mk) kb->mk->last_key_val = (uint8_t)ch;
                kb->key_down_count++;
                int f = 0; bool consumed = false, halted = false;
                for (; f < maxf; f++) {
                    if (!run_one_frame(computer)) { halted = true; break; }
                    if ((kb->kb_key_strobe & 0x80) == 0) { consumed = true; break; }
                }
                kb->key_down_count--;
                if (halted)
                    snprintf(result, rsz, "key $%02X halted@%d", ch, f);
                else if (consumed)
                    snprintf(result, rsz,
                             "key $%02X consumed after %d frame(s)", ch, f + 1);
                else
                    snprintf(result, rsz,
                             "key $%02X NOT CONSUMED in %d frame(s) -- the guest "
                             "never read $C000; it is not waiting for input",
                             ch, maxf);
            }
        } else {
            snprintf(result, rsz, "status=FAIL key-parse-fail");
        }
        return true;
    }
    if (!strncmp(line, "holdkey ", 8)) {
        unsigned int ch = 0;
        keygloo_state_t *kg =
            (keygloo_state_t *)computer->get_module_state(MODULE_KEYGLOO);
        if (sscanf(line + 8, "%x", &ch) == 1 && kg && kg->kg) {
            kg->kg->hold_key((uint8_t)ch);
        } else {
            /* BOTH of these shipped WITHOUT a status= prefix, so a caller
               branching on status=OK vs status=FAIL saw neither and had to
               string-match the failure text -- or, more likely, treat an
               unparseable reply as success. verbcheck's "every reply carries
               status=" probes BARE verbs; it never sent a bad argument, which
               is where both of these live. */
            snprintf(result, rsz, kg
                     ? "status=FAIL holdkey-parse-fail -- usage: holdkey <hex>"
                     : "status=FAIL holdkey-no-keygloo -- this machine has no ADB keyboard");
        }
        return true;
    }
    return false;
}

// cpu snapshot — honest KBD from module latch (status=OK prefix for harness).
inline bool try_cpu(const char *line, char *result, size_t rsz,
                    computer_t *computer) {
    if (strncmp(line, "cpu", 3) != 0 || (line[3] != 0 && line[3] != ' '))
        return false;
    char st[192];
    format_cpu_line(computer, st, sizeof st);
    snprintf(result, rsz, "status=OK cpu %s", st);
    return true;
}

// read / setreg / cycles / bp / stack — agent hands + timing mark + breakpoint.
inline bool try_regs(const char *line, char *result, size_t rsz,
                     computer_t *computer) {
    /* verify <addr> <len> <file> -- compare guest memory against a host file
       HERE, and answer with the verdict rather than the bytes.

       Every byte-comparison gate in the harness does the same three things:
       `read` a region to a file, load both files host-side, and walk them for
       the first difference. That is a lot of I/O to answer one question, and --
       more to the point -- the ANSWER then lives in harness code instead of in
       the status= contract. A suite can get the comparison wrong (one of them
       printed "byte-identical" beside a FAIL because its detail text only
       handled the differs case) and nothing about the rail would notice.

       So the comparison moves to where the data already is. Same principle the
       audio probe applies -- aggregate at the source, ship the conclusion, not
       the samples -- and the same reason: the interesting output is four
       numbers, not four kilobytes.

       The first differing offset is the whole point of the reply. "They differ"
       sends a reader back to a hex dump; "differ at 256" is a diagnosis. */
    if (!strncmp(line, "verify ", 7)) {
        uint32_t addr = 0; int len = 0, off = 0;
        char abuf[64] = {0};
        if (sscanf(line + 7, "%63s %d %n", abuf, &len, &off) < 2 || len <= 0 ||
            !parse_addr(abuf, &addr)) {
            snprintf(result, rsz, "status=FAIL verify-parse-fail -- usage: verify <addr|BANK:addr> <len> <file>");
            return true;
        }
        const char *path = line + 7 + off;
        FILE *vf = fopen(path, "rb");
        if (!vf) {
            snprintf(result, rsz, "status=FAIL verify-no-file '%s'", path);
            return true;
        }
        std::vector<uint8_t> want((size_t)len);
        size_t got = fread(want.data(), 1, (size_t)len, vf);
        fclose(vf);
        if (got != (size_t)len) {
            // A short file is NOT a mismatch at byte `got` -- it is a broken
            // expectation, and saying so keeps the two apart.
            snprintf(result, rsz,
                     "status=FAIL verify-short-file '%s' holds %llu of %d byte(s)",
                     path, (unsigned long long)got, len);
            return true;
        }
        /* USE rail_video_base, NOT dynamic_cast<MMU_II*>. MMU_IIgs is not in the
           MMU_II hierarchy, so the cast returns null on a IIgs -- and this verb
           originally fell back to probe_peek for a bank-01 request instead of
           reading aux at all. It did not fail; it answered plausibly about the
           wrong memory, and a `verify 01:6000` PASS was then used to conclude
           that a resource stage had worked. That conclusion was unsupported.
           The hazard is documented at the top of this file and this code was
           written anyway, which is the argument for the explicit refusal below
           rather than for another careful cast. */
        // rail_CPU_ram_base, not rail_video_base: `01:` means the bank guest
        // code addresses, which is what `load 01:` writes. Reading the Mega II
        // image here made a rail write unreadable through the rail on a IIgs.
        const uint8_t *flatv = rail_cpu_ram_base(computer);
        const bool wants_aux = (((addr >> 16) & 0xFF) == 1);
        if (wants_aux && !flatv) {
            // Refuse rather than silently reading somewhere else. A verb that
            // answers about memory it could not reach is worse than one that
            // cannot answer.
            snprintf(result, rsz,
                     "status=FAIL verify-no-aux-image -- bank 01 requested but this "
                     "machine exposes no flat main+aux image");
            return true;
        }
        const bool aux = wants_aux;
        int diff = -1; uint8_t gb = 0;
        for (int i = 0; i < len; i++) {
            uint8_t b = aux
                ? flatv[0x10000 + (((addr & 0xFFFF) + (uint32_t)i) & 0xFFFF)]
                : rail_mmu(computer)->probe_peek(addr + (uint32_t)i);
            if (b != want[(size_t)i]) { diff = i; gb = b; break; }
        }
        if (diff < 0) {
            snprintf(result, rsz, "status=OK verify %d byte(s) identical%s",
                     len, aux ? " (bank 01 aux)" : "");
        } else {
            snprintf(result, rsz,
                     "status=FAIL verify-differs at %d guest=$%02X file=$%02X (of %d)",
                     diff, gb, want[(size_t)diff], len);
        }
        return true;
    }
    if (!strncmp(line, "read ", 5)) {
        // Accept the same BB:AAAA form `load` accepts.
        //
        // It did not: `%x` stops at the colon, so `read 01:6000 …` returned
        // read-parse-fail while `load 01:6000 …` had just succeeded. Being able
        // to write somewhere you cannot read back makes the write unverifiable,
        // which is the one thing an actuator must never be.
        uint32_t addr = 0; int len = 0, off = 0;
        char abuf[64] = {0};
        if (sscanf(line + 5, "%63s %d %n", abuf, &len, &off) >= 2 && len > 0 &&
            parse_addr(abuf, &addr)) {
            FILE *rf = fopen(line + 5 + off, "wb");
            if (rf) {
                int unreadable = 0;
                // Bank 1 is the aux 64K, read the same way `load` writes it and
                // the vram dump already reads it. probe_peek does not route bank
                // bits on a IIe, so without this a caller can write aux and never
                // read it back -- which makes the write unverifiable.
                // Same helper `verify` uses, for the same reason: the cast to
                // MMU_II returns null on a IIgs, and this branch then fell
                // through to the main-memory path below -- answering status=OK
                // about the wrong bank for a request that explicitly named 01.
                const uint8_t *flat = rail_cpu_ram_base(computer);
                if (((addr >> 16) & 0xFF) == 1 && !flat) {
                    fclose(rf);
                    snprintf(result, rsz,
                             "status=FAIL read-no-aux-image -- bank 01 requested but this "
                             "machine exposes no flat CPU RAM image");
                    return true;
                }
                if (flat && ((addr >> 16) & 0xFF) == 1) {
                    for (int i = 0; i < len; i++) {
                        uint8_t b = flat[0x10000 + (((addr & 0xFFFF) + i) & 0xFFFF)];
                        fwrite(&b, 1, 1, rf);
                    }
                    fclose(rf);
                    snprintf(result, rsz, "status=OK read bank=01 aux %d byte(s)",
                             len);
                    return true;
                }
                /* TWO DIFFERENT QUESTIONS, and only one of them is
                   probe_readable's.
                   
                   probe_readable answers "is this page backed by memory?".
                   What a caller reading $C0xx actually needs to know is "does
                   this byte reflect the device?" -- and for the soft-switch and
                   register page the answer is never yes on any Apple II.
                   
                   On a IIe the two happened to agree: $C0xx is handler-backed,
                   probe_readable said no, the warning fired. On a IIgs it does
                   have a read pointer, so probe_readable said YES and `read C000
                   16` returned sixteen zero bytes with status=OK -- while `vid`
                   reported TEXT=1. Same verb, same address, honest on one
                   machine and quietly wrong on the other, which is worse than
                   being wrong on both.
                   
                   $C100-$CFFF is excluded: slot ROM there is genuine readable
                   memory and dumping it is a legitimate thing to want. */
                int io_page = 0;
                for (int i = 0; i < len; i++) {
                    uint16_t lo = (uint16_t)((addr + i) & 0xFFFF);
                    if (lo >= 0xC000 && lo <= 0xC0FF) io_page++;
                    else if (!rail_mmu(computer)->probe_readable(addr + i)) unreadable++;
                    uint8_t b = rail_mmu(computer)->probe_peek(addr + i);
                    fwrite(&b, 1, 1, rf);
                }
                unreadable += io_page;
                fclose(rf);
                /* THREE OUTCOMES, and the old code collapsed them into two.
                 *
                 * probe_peek is observation-FREE but not observation-COMPLETE:
                 * on a handler-backed page -- all of $C0xx, often LC/ROM and the
                 * IIgs shadowed banks -- it returns floating bus, a plausible
                 * byte that is pure noise. The hazard note on probe_peek lists
                 * five instruments that shipped confident fiction because of it.
                 *
                 * This verb did check probe_readable, which is right, and then
                 * reported the warning as "ok WARNING ..." -- with no status=
                 * field at all. So the one reply whose entire purpose is to tell
                 * a caller its data is not real was also the one reply a caller
                 * keying on status=(OK|FAIL) could not parse. It read as silence.
                 *
                 * Now: some bytes unreadable is OK-with-warning, because the rest
                 * are genuine. NONE readable is a FAIL -- the caller asked to see
                 * an address and learned nothing, and "I cannot see this" is the
                 * honest answer probe_readable exists to give. */
                if (unreadable >= len) {
                    snprintf(result, rsz,
                             "status=FAIL read-unreadable %d/%d byte(s) — the whole "
                             "range is handler-backed (floating bus, not memory). "
                             "The file holds bus noise, not data. For $C0xx state "
                             "use the owning verb: vid, screen, iolog, speaker, "
                             "devstate <dev>.",
                             unreadable, len);
                } else if (unreadable) {
                    snprintf(result, rsz,
                             "status=OK read %d byte(s) WARNING %d of them not "
                             "probe-readable (handler-backed page -> floating bus, "
                             "not memory)",
                             len, unreadable);
                } else {
                    snprintf(result, rsz, "status=OK read %d byte(s)", len);
                }
            } else {
                snprintf(result, rsz, "status=FAIL read-fail");
            }
        } else {
            snprintf(result, rsz, "status=FAIL read-parse-fail");
        }
        return true;
    }
    if (!strncmp(line, "setreg ", 7)) {
        char rn[16]; unsigned long v = 0;
        if (sscanf(line + 7, "%15s %lx", rn, &v) == 2) {
            cpu_state *c = computer->cpu;
            bool ok = true;
            if      (!strcmp(rn, "a"))   c->a  = (uint16_t)v;
            else if (!strcmp(rn, "x"))   c->x  = (uint16_t)v;
            else if (!strcmp(rn, "y"))   c->y  = (uint16_t)v;
            else if (!strcmp(rn, "sp"))  c->sp = (uint16_t)v;
            else if (!strcmp(rn, "p"))   c->p  = (uint8_t)v;
            else if (!strcmp(rn, "d"))   c->d  = (uint16_t)v;
            else if (!strcmp(rn, "pc"))  c->full_pc = (uint32_t)(v & 0xFFFFFF);
            // THE EMULATION FLAG, because there was no way to set it and it is
            // needed constantly. `run <n>` advances n VIDEO FRAMES and leaves the
            // IIgs ROM wherever it happened to be -- which is NATIVE mode, a
            // state a 128K Apple II cannot be in. Every harness that splices 6502
            // code in after a `run` inherits it, and slot firmware called from
            // there does not survive. The workaround was to poke `38 FB 4C ..`
            // (SEC / XCE / JMP) and run it, which is three verbs and a scratch
            // address to express one bit.
            //
            // Entering emulation mode does MORE than set the bit: XCE forces M
            // and X to 1 and truncates the index and stack high bytes. Setting
            // E alone would leave 16-bit registers live in a mode that has none,
            // which is not a state the CPU can reach and not one worth being
            // able to fake. Mirrored from OP_XCE_IMP in base_6502.cpp.
            else if (!strcmp(rn, "e")) {
                c->E = (v & 1) ? 1 : 0;
                if (c->E) { c->x_hi = 0; c->y_hi = 0; c->sp_hi = 0x01;
                            c->_M = 1;  c->_X = 1; }
            }
            else ok = false;
            snprintf(result, rsz, ok
                     ? "status=OK setreg %s=$%lX (DELIBERATE splice)"
                     : "status=FAIL setreg-unknown-%s", rn, v);
        } else {
            snprintf(result, rsz, "status=FAIL setreg-parse-fail");
        }
        return true;
    }
    if (!strncmp(line, "cycles", 6) && (line[6] == 0 || line[6] == ' ')) {
        // VALID timing = in-command cycles= on run/step/run-until.
        // Cross-ack delta of two `cycles` replies is unreliable (see AGENTIC_ORACLE).
        uint64_t cyc = computer->clock ? computer->clock->get_cycles() : 0;
        static uint64_t s_cyc_mark = 0;
        if (strstr(line, "reset")) {
            s_cyc_mark = cyc;
            snprintf(result, rsz,
                     "status=OK cycles=%llu mark=reset "
                     "WARN=prefer-in-command-deltas (run/step/run-until)",
                     (unsigned long long)cyc);
        } else {
            snprintf(result, rsz,
                     "status=OK cycles=%llu delta_from_mark=%llu "
                     "WARN=cross-ack-deltas-unreliable use-run-until-cycles",
                     (unsigned long long)cyc,
                     (unsigned long long)(cyc - s_cyc_mark));
        }
        return true;
    }
    // Every ack on this rail leads with status=; these three did not, so a caller
    // parsing acks generically saw a breakpoint set, cleared, or failed to parse
    // as equally unclassifiable. Bare `bp` did not match at all (the old test
    // required a trailing space) and fell through to unknown-cmd.
    if (!strncmp(line, "bp", 2) && (line[2] == 0 || line[2] == ' ')) {
        const char *arg = (line[2] == ' ') ? line + 3 : "";
        while (*arg == ' ') arg++;
        if (!*arg) {
            if (g_iigs_break_enabled)
                snprintf(result, rsz, "status=OK bp @%02X/%04X armed",
                         (unsigned)((g_iigs_break_addr >> 16) & 0xFF),
                         (unsigned)(g_iigs_break_addr & 0xFFFF));
            else
                snprintf(result, rsz, "status=OK bp off");
        } else if (!strcmp(arg, "off")) {
            g_iigs_break_enabled = false;
            snprintf(result, rsz, "status=OK bp cleared");
        } else {
            uint32_t a = 0;
            if (parse_addr(arg, &a)) {
                g_iigs_break_addr = a;
                g_iigs_break_enabled = true;
                snprintf(result, rsz, "status=OK bp @%02X/%04X armed "
                         "(halts when PC reaches it; run/step/resume continue past it)",
                         (unsigned)((a >> 16) & 0xFF), (unsigned)(a & 0xFFFF));
            } else {
                snprintf(result, rsz, "status=FAIL bp-parse-fail '%s' -- "
                         "usage: bp <addr|BANK:addr|off>, hex", arg);
            }
        }
        return true;
    }
    /* audio -- the generated sample stream, which nothing could see.

       Every other audio check in this tree is at the REGISTERS: periphcheck
       round-trips DOC registers and sound RAM, spkcheck counts $C030 toggles and
       times them. None of that observes a SAMPLE. A chip that is clocked and
       addressed correctly but emits silence -- or emits one value forever --
       passes all of it.

         audio                the DOC source (see below), and how many exist
         audio doc | sfx      one named source: doc = Ensoniq, sfx = drive sounds
         audio on | off       arm/disarm ALL sources (arming resets the counters)
         audio reset          zero all counters, stay armed

       The aggregates alone cannot distinguish a working stereo stream from one
       that dropped a side, so the per-channel breakdown is always reported, and
       ch= states the observed width rather than leaving it to be inferred.
       ch=0 means no batch has been seen since arming. Interleave slot 0 is
       reported as l_*, slot 1 as r_*; which side that is in the air is the
       emulator's TN #19 convention, not something this probe asserts.

       SOURCES ARE NEVER SUMMED. The Ensoniq and the drive effects are separate
       devices on separate paths, and the DOC is usually busy -- so one combined
       figure would let "some audio happened" pass for "the DRIVE made a sound".
       Every line names its src= for that reason, and the bare form reports the
       DOC because that is what it has always reported; it is not "all audio".

       unread= counts batches a source declined because the sample format was
       not one it can read. Without it, an unreadable format and silence would
       produce the same zeros.                                                */
    if (!strncmp(line, "audio", 5) && (line[5] == 0 || line[5] == ' ')) {
        const char *arg = (line[5] == ' ') ? line + 6 : "";
        while (*arg == ' ') arg++;
        int which = audio_probe::SRC_DOC;
        if (!strcmp(arg, "on"))       audio_probe::arm(true);
        else if (!strcmp(arg, "off")) audio_probe::arm(false);
        else if (!strcmp(arg, "reset")) audio_probe::reset();
        else if (!strcmp(arg, "doc")) which = audio_probe::SRC_DOC;
        else if (!strcmp(arg, "sfx")) which = audio_probe::SRC_SFX;
        else if (*arg && strcmp(arg, "status")) {
            snprintf(result, rsz, "status=FAIL audio-need: [status]|doc|sfx|on|off|reset");
            return true;
        }
        const audio_probe::source_t &S = audio_probe::g_src[which];
        const char *name = (which == audio_probe::SRC_SFX) ? "sfx" : "doc";
        const uint64_t n = S.samples;
        // Per-channel averages divide by FRAMES, not by total samples: one frame
        // contributes one sample to each channel, so frames is that channel's
        // own count. Dividing by the sample total would halve every stereo
        // channel average and make a healthy stream look like it lost level.
        const uint64_t fr = S.frames;
        snprintf(result, rsz,
                 "status=OK audio on=%d src=%s sources=%d"
                 " samples=%llu nonzero=%llu min=%d max=%d avg_abs=%llu"
                 " ch=%d frames=%llu unread=%llu"
                 " l_nz=%llu l_min=%d l_max=%d l_avg=%llu"
                 " r_nz=%llu r_min=%d r_max=%d r_avg=%llu",
                 audio_probe::g_on ? 1 : 0, name, (int)audio_probe::N_SRC,
                 (unsigned long long)n,
                 (unsigned long long)S.nonzero,
                 (int)S.min, (int)S.max,
                 (unsigned long long)(n ? S.abs_sum / n : 0),
                 S.channels,
                 (unsigned long long)fr,
                 (unsigned long long)S.unread,
                 (unsigned long long)S.ch_nonzero[0],
                 (int)S.ch_min[0], (int)S.ch_max[0],
                 (unsigned long long)(fr ? S.ch_abs_sum[0] / fr : 0),
                 (unsigned long long)S.ch_nonzero[1],
                 (int)S.ch_min[1], (int)S.ch_max[1],
                 (unsigned long long)(fr ? S.ch_abs_sum[1] / fr : 0));
        return true;
    }
    /* session -- what is armed right now, and one command to disarm it all.

       PROBE STATE HAS NO OWNER. `cov on`, `audio on`, `tbuf on`, `iolog on`,
       `paddle`, `joymode` and the CPU trace flag all persist for the life of
       the session with nothing recording who set them. A suite that exits
       without disarming leaves the machine armed for whatever runs next, and
       there was no way to ask "what is armed" or to clear it in one move.

       That is not theoretical. A runaway probe left a session in a state that
       `validate.ps1 -SkipBuild` then REUSED, producing a COREIMG failure --
       the language-card core reading as zeros -- that looked exactly like a
       regression in the engine. It was contamination, and establishing that
       cost a debugging round.

       WHAT IT DOES NOT COVER, stated rather than implied: valtrap, itrace,
       tbtrace and callstream keep their state elsewhere and are not reachable
       from here yet. `session` lists them as unknown rather than reporting a
       confident zero -- a reset that silently misses half the state is worse
       than no reset, because it licenses the assumption that the machine is
       clean.

         session               what is armed
         session reset         disarm everything this verb can reach          */
    if (!strncmp(line, "session", 7) && (line[7] == 0 || line[7] == ' ')) {
        const char *arg = (line[7] == ' ') ? line + 8 : "";
        while (*arg == ' ') arg++;
        gamec_state_t *sgc = (gamec_state_t *)computer->get_module_state(MODULE_GAMECONTROLLER);
        const bool doing = !strcmp(arg, "reset");
        if (*arg && !doing && strcmp(arg, "status")) {
            snprintf(result, rsz, "status=FAIL session-need: [status]|reset");
            return true;
        }
        if (doing) {
            audio_probe::arm(false);
            a2gspu_cov_off();
            g_io_trace_enabled = false;
            io_trace_reset();
            if (computer->cpu) computer->cpu->trace = 0;
            if (sgc) { sgc->inject_active = false;
                       sgc->joystick_mode = JOYSTICK_APPLE_GAMEPAD; }
        }
        snprintf(result, rsz,
                 "status=OK session %s audio=%d cov=%d iolog=%d tbuf=%d "
                 "paddle_inject=%d joymode=%s "
                 "[not covered: valtrap itrace tbtrace callstream]",
                 doing ? "reset" : "status",
                 audio_probe::g_on ? 1 : 0,
                 g_cov_on ? 1 : 0,
                 g_io_trace_enabled ? 1 : 0,
                 (computer->cpu && computer->cpu->trace) ? 1 : 0,
                 (sgc && sgc->inject_active) ? 1 : 0,
                 !sgc ? "-" : (sgc->joystick_mode == JOYSTICK_ATARI_DPAD  ? "atari"
                             : sgc->joystick_mode == JOYSTICK_APPLE_MOUSE ? "mouse"
                                                                          : "gamepad"));
        return true;
    }
    /* tbuf -- the CPU trace ring, which only the on-screen debugger could read.
       The emulator records every instruction with its registers, its effective
       address, its data and (since the 9420cac port) whether the access was a
       read or a write -- and the one consumer that cannot look at a window had
       no route to any of it. Exactly the black box devstate was.

       This is also what makes the eaddr fix checkable: itrace resolves the
       effective address itself, so it never showed the bug. The ring is the
       consumer that carried it.

         tbuf                is tracing on, and how many entries are held
         tbuf on | off       start/stop filling the ring
         tbuf clear          discard what is held
         tbuf dump <f> [n]   decode the newest n entries (default all), oldest
                             first, so a dump reads in execution order          */
    if (!strncmp(line, "tbuf", 4) && (line[4] == 0 || line[4] == ' ')) {
        const char *arg = (line[4] == ' ') ? line + 5 : "";
        while (*arg == ' ') arg++;
        cpu_state *c = computer->cpu;
        if (!c || !c->trace_buffer) {
            snprintf(result, rsz, "status=FAIL tbuf-no-buffer -- no trace ring on this machine");
            return true;
        }
        system_trace_buffer *tb = c->trace_buffer;
        if (!*arg || !strcmp(arg, "status")) {
            snprintf(result, rsz, "status=OK tbuf on=%d held=%zu capacity=%zu",
                     c->trace ? 1 : 0, tb->count, tb->size);
        } else if (!strcmp(arg, "on")) {
            c->trace = true;
            snprintf(result, rsz, "status=OK tbuf on held=%zu capacity=%zu", tb->count, tb->size);
        } else if (!strcmp(arg, "off")) {
            c->trace = false;
            snprintf(result, rsz, "status=OK tbuf off held=%zu", tb->count);
        } else if (!strcmp(arg, "clear")) {
            tb->head = tb->tail = tb->count = 0;
            snprintf(result, rsz, "status=OK tbuf cleared on=%d", c->trace ? 1 : 0);
        } else if (!strncmp(arg, "dump", 4) && (arg[4] == 0 || arg[4] == ' ')) {
            const char *p = arg + 4;
            while (*p == ' ') p++;
            char path[512] = {0};
            long want = 0;
            if (sscanf(p, "%511s %ld", path, &want) < 1 || !path[0]) {
                snprintf(result, rsz, "status=FAIL bad-args -- usage: tbuf dump <file> [n]");
            } else if (tb->count == 0) {
                // Never claim a dump for an empty ring: that is the cov defect.
                snprintf(result, rsz, "status=FAIL tbuf-empty -- nothing recorded; "
                         "`tbuf on` then run, and check `tbuf` says on=1");
            } else {
                size_t n = tb->count;
                if (want > 0 && (size_t)want < n) n = (size_t)want;
                FILE *f = fopen(path, "wb");
                if (!f) {
                    snprintf(result, rsz, "status=FAIL tbuf-open-fail %s", path);
                } else {
                    size_t start = (tb->head + tb->size - n) % tb->size;
                    for (size_t i = 0; i < n; i++) {
                        system_trace_entry_t *e = tb->get_entry((start + i) % tb->size);
                        char *dec = tb->decode_trace_entry(e);
                        char lbuf[512];
                        snprintf(lbuf, sizeof lbuf, "%s", dec ? dec : "(decode-failed)");
                        for (char *q = lbuf; *q; q++) if (*q == '\r' || *q == '\n') { *q = '\0'; break; }
                        fprintf(f, "%s eaddr=%06X rw=%c\n", lbuf,
                                (unsigned)(e->eaddr & 0xFFFFFF), e->f_write ? 'W' : 'R');
                    }
                    fclose(f);
                    snprintf(result, rsz, "status=OK tbuf dumped %zu of %zu entries to %s",
                             n, tb->count, path);
                }
            }
        } else {
            snprintf(result, rsz, "status=FAIL tbuf-need: [status]|on|off|clear|dump <file> [n]");
        }
        return true;
    }
    if (!strncmp(line, "stack", 5) && (line[5] == 0 || line[5] == ' ')) {
        int n = 16;
        if (line[5] == ' ') n = atoi(line + 6);
        if (n < 1) n = 1;
        if (n > 48) n = 48;
        uint16_t sp = (uint16_t)(computer->cpu->sp & 0xFFFF);
        char *p = result;
        size_t rem = rsz;
        /* status= like every other verb. This replied with a bare "SP=...",
           so a caller keying on status=(OK|FAIL) -- which is the documented
           contract and what every other reply carries -- silently skipped
           it. The SP= and the bytes are unchanged, only prefixed. */
        int w = snprintf(p, rem, "status=OK stack SP=%04X", sp);
        p += w; rem -= (size_t)w;
        for (int i = 1; i <= n && rem > 4; i++) {
            uint8_t b = rail_mmu(computer)->probe_peek((uint16_t)(sp + i));
            w = snprintf(p, rem, " %02X", b);
            p += w; rem -= (size_t)w;
        }
        return true;
    }
    return false;
}


